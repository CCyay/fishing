#!/bin/sh
# ============================================================================
#  滤饵的 1.59 到底是真值还是下限？——「尺子值多少」那一跑〔2026-10-22〕
# ============================================================================
#
#  用户的质疑（原话）：
#   「3洗2 怎么会输给 换水？
#     手牌3张+抽的3张，从6张里面选自己要的4张 对比 从3张中最多选3张不要的退回
#     3洗2 能帮助自己拿到想要的牌，而换水只是去掉自己不要的牌
#     我很怀疑这个分值」
#
#  这个质疑指着一个**真的口径错误，而且是我的**：我拿滤饵 1.59 减换水 1.74
#  说「差 0.15 在噪声里，两件分不开」。**那两个数的身份不一样** ——
#
#    换水 1.74 **接近真值**：`SWAP_WASTE=0`（完全不挑、强制换满 3 张）只掉
#      0.27 分。换水的价值几乎不来自「挑得准」，它来自**量**（真换掉 2.884/3 张）。
#      ⚠ 而「强制换满」对换水**恰好就是完全不挑** —— 手里 3 张全退光了，
#      挑的顺序不影响结果。所以那一格是干净的「不挑」对照。
#
#    滤饵 1.59 **可能是下限**：它只退 2/6，价值全押在尺子上，而
#      `ai.swapPick`（ai.js:774）的打分是
#          (钓得着||J ? 100 : 0) + extra*20 + card.value
#      —— 在「全是废牌」那个区间里它只剩 `card.value`（点数大小）排序，
#      而点数大小跟「下回合钓不钓得着」几乎无关（堆会被对手改掉）。
#
#  照 CLAUDE.md 凝水那条：**挑牌类的 X 是下限，而「那个数本来不准」**，
#  重跑一百遍还是那个数。**拿一个下限去跟一个近真值比大小，得出的「分不开」是假的。**
#
#  ---- 这一跑加的东西（都在 tools/md-sim/rules.js） ----
#  旋钮 `SIFT_PICK='rand'`：盲退、完全不挑（照 `FUEL_BLIND` 的形状）。
#    **默认档 − rand 档 = 这把尺子值多少分。**
#    ⚠ rand 档多消耗一次 rng → 跟默认档**不是同一批牌序**，
#      两档相减只能靠局数（20000 局，se 0.11），不能靠同种子逐位比。
#  诊断口 `poolSize` / `poolUseful` / `backUseful`：
#    池子多大、其中几张**现在就钓得着**、退掉的里误伤了几张。
#
#  ⚠ 默认值这一跑翻了：`SIFT_DRAW/SIFT_BACK` 从 `1/1` → **`3/2`**
#    （用户定的 N=3）。照「旋钮的默认值 = 游戏里那件技能的样子」。
#    **一个旧数都不废** —— 以前每跑都显式传参，默认档从没被引用过。
#    第 1 节那个版本锚就是在验这一点。
#
#  口径：`vs X X -n 20000`，A 槽 = 江口闸官 `--role lock --slot 0`（定价锚槽）、
#        ♥ 槽 = `--role mirror --slot 0`。**X = 两侧平均、D = 打印那个差的一半。**
#        诊断 4000 局。R3 规则档。
# ============================================================================

set -u
cd "$(dirname "$0")/../.." || exit 1

N=20000
ND=4000
V="node tools/md-sim/sim.js vs"
D="node tools/md-sim/proto-diag.js"
A="--role lock --slot 0"
H="--role mirror --slot 0"

pick() { grep -E '手里：|先手 − 后手|镜像协同' | head -4; }
diag() { grep -E '出牌|sift:|swap:'; }

job()  { printf -- '-- %s\n' "$1"; shift; env "$@" 2>&1 | pick; }
jobd() { printf -- '-- %s\n' "$1"; shift; env "$@" 2>&1 | diag; }

echo '################ 0. 结构闸（我动过 rules.js，这次必跑）################'
if node tools/md-sim/check.js >/tmp/sift-chk.txt 2>&1; then
  echo '全过。'
  grep -E '保护：' /tmp/sift-chk.txt
else
  echo '✗ check.js 没过 —— 下面的数一个都别看。'
  tail -25 /tmp/sift-chk.txt
  exit 1
fi

echo
echo '################ 1. 版本锚：翻完默认值，滤饵还是那件技能吗 ################'
echo '〔不传任何 SIFT_* 参数。**该逐位复现 +1.52 / +1.66**（上一跑显式传 3/2 的数）。'
echo '  对不上 = 默认值翻错了或者我加 SIFT_PICK / 三个计数口时碰坏了别的，'
echo '  **这一跑的数一个都不能用**。模拟器定种，没碰到的东西该逐位不变。〕'
job '滤饵 默认档（= 抽3洗2）· A 槽 ← 该复现 +1.52 / +1.66' $V sift sift -n $N $A
job '滤饵 默认档 · ♥ 槽 ← 该复现 +4.05 / +4.32' $V sift sift -n $N $H

echo
echo '################ 2. 池子里到底有没有东西可挑 ################'
cat <<'EOF'
〔这一节是用户那个质疑的直接答案，三个数要一起读：

   `poolUseful / poolSize` = **退牌之前**池子里「现在就钓得着」的比例（J 算）。
     低 → 池子几乎全是废牌，「从 6 张选 4 张」里的「选」**没有信息可用**，
          尺子只剩点数大小 → 1.59 就接近真值，而死因在设计层不在测量。
     高 → 有东西可挑，那第 3 节的 rand 档应该掉很多。

   `backUseful / returned` = 退掉的里**误伤**了几张钓得着的牌。
     换水有一道「见好就收」闸（`SWAP_WASTE`，第二张起只换真废牌），
     而滤饵按用户的 desc（「选择 N 张牌洗回牌组」）是**强制退满**，没有那道闸。
     这一口量的就是那个不对等 —— 它是**这件技能自带的代价**，不是 bug。

 ⚠ 参照：换水那边手里 3 张平均有 **2.884 张**是废牌（96%）。
   滤饵的池子要是也这个比例，6 张里就有 5.8 张废牌。〕
EOF
jobd '滤饵 默认档 · 诊断' $D sift $ND 0 lock

echo
echo '################ 3. 下限尺子：盲退（SIFT_PICK=rand）################'
echo '〔**默认档 − 这一格 = `ai.swapPick` 这把尺子值多少分。**'
echo '  对照：换水的同一笔是 **1.74 − 1.47 = 0.27 分**（`SWAP_WASTE=0`，已量）。'
echo '  ⚠ rand 档牌序跟默认档不同（多耗一次 rng）→ 靠局数相减，别指望逐位。〕'
job  '滤饵 SIFT_PICK=rand · A 槽' SIFT_PICK=rand $V sift sift -n $N $A
job  '滤饵 SIFT_PICK=rand · ♥ 槽' SIFT_PICK=rand $V sift sift -n $N $H
jobd '滤饵 SIFT_PICK=rand · 诊断' SIFT_PICK=rand $D sift $ND 0 lock

echo
echo '################ 4. 尺子值随池子变大怎么走（N=6）################'
echo '〔滤饵退 N−1 张、池子 N+3 张。N 越大池子越大，而「在废牌里排序」'
echo '  这件事越没把握。拿 N=6 的 ai−rand 对 N=3 的 ai−rand，'
echo '  给出**尺子值的斜率** —— 它决定「把 N 做大」是在加强度还是在加噪声。'
echo '  参照：N=6 的 ai 档已量 = X 3.04（A 槽）。〕'
job  '滤饵 N=6 · SIFT_PICK=rand · A 槽' SIFT_DRAW=6 SIFT_BACK=5 SIFT_PICK=rand $V sift sift -n $N $A
jobd '滤饵 N=6 · 默认尺子 · 诊断' SIFT_DRAW=6 SIFT_BACK=5 $D sift $ND 0 lock

echo
echo '################ 5. 怎么读 ################'
cat <<'EOF'
一、**先核第 1 节那两个版本锚**（+1.52/+1.66、+4.05/+4.32）。
   对不上 → 后面全部作废，先修默认值 / 计数口。

二、再读第 2 节 `poolUseful/poolSize`。它把结论劈成两条路：

   池子里废牌占绝大多数（比如 ≥85%）
     → 「从 6 张里选自己要的 4 张」这句话在实战里**兑现不了** ——
       因为那 6 张里本来就没有 4 张「自己要的」。
       **那不是 AI 挑得笨，是没得挑**，1.59 接近真值。
       而这时候用户的直觉仍然指着一个真东西，只是落点不同：
       它该改的是**时点**（现在在 `afterPlay` 挑，看的是当前堆，
       可这几张要到下回合才用，堆已经被对手改过了），不是改 N。

   池子里有相当比例钓得着
     → 那 rand 档该掉得多，1.59 是下限，**用户的直觉直接对**，
       而这件技能的真值要用一把更好的尺子重量（那是另一轮）。

三、第 3 节那个差（ai − rand）跟换水的 0.27 比：
   **明显大于 0.27** → 滤饵吃尺子、换水不吃，两件的数**本来就不能直接比大小**，
     我那句「差 0.15 分不开」是错的口径对比，得撤。
   **跟 0.27 差不多或更小** → 两件都不吃尺子，1.59 vs 1.74 可以比，
     那换水赢在量（3.884 张新牌 vs 滤饵 2.07 张），这是个干净的结论。

四、⚠ **定价、命名、上不上架一个都没定** —— 这一跑只出数，而且只动模拟器。
EOF
