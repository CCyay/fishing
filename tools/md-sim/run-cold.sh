#!/bin/sh
# 【寒流】那个槽的形状矩阵：**用户给的三个驻场效果**〔2026-10-20〕
#
# 为什么挂在寒流这个槽上：三件的 `desc` 里「驻场」「自带结冰」两句跟寒流
# 一字不差，而那两句在 rules.js 里是三条分散的路（ICE_VOID / ICE_SINK /
# selfFrost → 手冰表 → iceBlind → frostOnLand）。自己新写一份必然漏一条，
# **凌流就是那么死的**（手写 addFrostAt 绕过 selfFrost，−2.16 全是 bug）。
# 挂原槽 → 那三条自动继承 → **五档之间差的只有「在场时做什么」那一句**。
#
# 口径 `vs coldhue coldhue`：role=lock（江口闸官）、slot=0（A，4 张）、
# 不带常驻技、n=20000 —— 跟台账那张 `all` 全表一字不差，所以每一格都能
# 直接跟寒流那一行的 +3.11 相减。
#
# ⚠ `vs` **会忽略 --n**（2026-10-20 查出来的，台账有记）—— 它恒用 20000 局。
#    所以这儿不传 N，免得看着像在控局数。`pair` 认 --n。
#
# 五档：
#   hue       现行寒流（**零点**，回归验证该回到 +3.11）
#   match     「驻场，打出的牌匹配后获得【结冰】」
#   pick      「驻场，自带结冰，打出带【结冰】的牌后，选择 1 张手牌带上【结冰】」
#   board     「…使全场带上【结冰】」（堆上所有牌 + 自己手牌）
#   boardfoe  同上，**「全场」含对手手牌**那个读法（= 白送他钥匙）
#
# ⚠ 后四档**跟现行 `desc` 不符** —— 它们是用户提的三件的原型，
#   量出来的数不能当寒流的数。而 `board`/`boardfoe` 是同一句话的两种读法
#  （`draw-terms.uts` 里**没有「全场」这个词条**），所以两档都量、不替用户定。
#
# 用户要求「跟藏凌一起量」—— 所以每档后面跟一个 `pair coldhue hide`。
# 那一格问的是「这三件要靠配合才够分吗」：族内配合上一轮量过三组
#（协同 −0.03 / −1.02 / +0.28），这儿是把用户的新形状也放进同一个口径。
#
# ---- 结果（2026-10-20，五档全跑完）----
#   hue +3.11〔零点，回归对上台账〕/ match +2.22 / pick +1.43 /
#   board **+5.39（超档）** / boardfoe **−5.21**，|D| 全 ≤ 0.16。
#   配藏凌：5.06 / 4.01 / 3.54 / 7.04 / −3.51，**协同五格全为负**
#   （−1.02 / −1.18 / −0.86 / −1.33 / −1.27）。
#
#   boardonly〔用户定稿「仅堆上」〕：**−0.31**，配藏凌 **3.20**、
#   **协同 +0.54 —— 九格里唯一为正的一格**。维持率 64.6% → **18.0%**
#  （= 1.68 次/边-局 = 只在打出技能牌那一手铺，驻场那句白写）。
#
# ---- ⚠ 第一版跑出来的四个数全是 bug 的数，别信 ----
#
#   第一版在两处判定里多写了一个 `has(skills, SK.COLDHUE)`，那是
#  「**这一手打出的正是技能牌**」—— 等于把「驻场」压成一次性。
#   A 槽只有 4 张牌，所以发动率掉到 **7.3%**。
#
#   | 档 | bug 下 | 修后 | 差 |
#   |---|---|---|---|
#   | match | −0.73 | +2.22 | **+2.95** |
#   | pick  | +0.35 | +1.43 | +1.08 |
#   | board | +1.93 | +5.39 | **+3.46** |
#   | boardfoe | −1.84 | −5.21 | **−3.37** |
#
#   **四个数全部反方向或翻倍，而两个档的结论整个掉个头**（board 从
#   「档内」变「超档」、match 从负变正）。病根照旧是那一条：
#   我抄了【留潮】的**位置**却没抄它的**判定**（留潮用 `heldAny`）。
#   而单看 X 看不出来 —— 抖出它的是诊断口里的发动率。
#   所以这个脚本的 grep 里保留「在场效果发动」那一行，别删。
#   boardonly 「全场」**仅堆上**（用户 2026-10-20 定稿的读法）——
#             它自己造不出钥匙，所以**协同该是正的**（头一个）
for m in ${MODES:-hue match pick board boardfoe boardonly}; do
  echo "######## COLD_MODE=$m · 单带 ########"
  COLD_MODE=$m node tools/md-sim/sim.js vs coldhue coldhue 2>&1 \
    | grep -E "手里|先手 − 后手|寒流那个槽|在场效果发动|钥匙|障碍|空转|正常的|恒假"
  echo
  echo "######## COLD_MODE=$m · 配藏凌 ########"
  COLD_MODE=$m node tools/md-sim/sim.js pair coldhue hide --n 20000 2>&1 \
    | grep -E "只带|两件都带|协同|在场效果发动|钥匙|障碍"
  echo
done
