#!/usr/bin/env bash
# 2026-10-21 ·【映照】升级档的**诊断口**：那张全表只给了 X，这一批问
# 「它到底做了几次」。照 CLAUDE.md 第四节：加旋钮就一起加计数口。
#
# ---- 这一批要解的三个具体疑点（全表跑完才冒出来的）----
#
# 一、A 槽里 **引火 / 吃水 / 削水 / 冻结 / 收色 / 满篓 / 窄口 的 Δ 是精确 +0.00**。
#     同种子下逐位相同 = 映照**一次都没改变过决策**。而同样这几件在 ♣ 槽
#     有的动了（引火 +0.64、吃水 +1.55）—— **同一个 `reflectScore`，
#     为什么一边恒不换一边换**？`kept / fires` 直接回答。
#
# 二、**压吃 A +2.67 而 ♣ −0.49**，方向都反了。猜法有两种而诊断分得开：
#     「A 槽那件本来被『只能减 1 点』卡死、映照把常量解开了」→ changed 高；
#     「♣ 槽是别的东西在抵消」→ changed 也高但分没上去。
#
# 三、**涨水 −4.71 / 涌潮 −4.14**（协同，♣）。可选档只在
#     `score > own`（收得更多）时才换，**那为什么换了反而亏**？
#     答案只能是「多收的那几张不值它破坏掉的东西」—— 而 changed 给出分母。
#
# ---- 读数的前提（这是这一批真正要钉死的那条）----
#
# `reflectScore`（rules.js:6140）**只调 `catchStart`**，可选档的闸
#（6165，`score > own`）用的是同一把尺子。所以映照换脸**只看「这一手
# 多收几张」，看不见任何别的价值轴**（harvestCount 那条收成线、驻场、
# 抽牌、贴标签全看不见）。
#
# 于是两类行的可信度完全不同，**而这一批就是去分这两类**：
#   changed ≈ 0 → 映照在那件技能旁边**根本没动过手**，
#                 协同 = −锚 是**挑牌器的盲区**，不是这个设计的性质；
#   changed 高而分掉 → 真冲突：闸用错了目标函数，每次换脸都是一次
#                 「拿那件技能的轴去换收成」的无控交易。
#
# 旋钮：ND=局数
set -u
ND=${ND:-4000}
cd "$(dirname "$0")/../.."
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

# key:名字:全表那一行的协同（A / ♣）
ROWS="
suited:顺色:+2.73:+8.29
hue:收色:-0.52:-0.63
peak:齐顶:+1.12:+3.52
hook:磁钩:+2.00:+2.95
probe:探潮:+0.81:+1.35
pushdraft:压吃:+2.67:-0.49
kindle:引火:-0.52:+0.01
draft:吃水:-0.52:+0.92
swell:涨水:-1.34:-4.71
risetide:涌潮:-2.65:-4.14
"

# ⚠ 顺色 和 收色 **进来是一对的**，而它们是这一批最尖的那个疑点：
#   `valuesOf`（rules.js:5570）把【顺色】【洪水】【收色】归在同一支 ——
#   「拿整个点数换一次按花色钓，点数整个不算」。**同一支**，而
#   顺色协同 +2.73 / +8.29（全表第一），收色 −0.52 / −0.63（恒 0 那一档）。
#   两件走同一条 `valuesOf` 分支却一个顶天一个纹丝不动 —— **这个我解释不了**，
#   而它正是「别拿印象当证据」那条：`changed/fires` 先给事实，再谈为什么。

for row in $ROWS; do
  k=${row%%:*}
  # ⚠ **第一个参数是「槽里插哪一件」** —— 这儿必须是 `$k` 本身，
  #   不是 `reflect`。第一版写成 `reflect` 了，于是槽里插的是映照自己，
  #   `reflectOn` 走 `has(skills, SK.REFLECT)` 直接为真，`REFLECT_WITH`
  #   根本没参与 —— **十行输出跟锚逐字相同**。
  #   〔这正是「失败是静默的」：跑得通、格式对、数也「合理」〕
  ( REFLECT_WITH=$k X=1 node tools/md-sim/proto-diag.js $k $ND 0 lock \
      >"$TMP/a_$k" 2>&1 ) &
  ( REFLECT_WITH=$k X=1 node tools/md-sim/proto-diag.js $k $ND 0 deepline \
      >"$TMP/c_$k" 2>&1 ) &
  # 同一件**不挂映照**那一跑 —— 两边的「分/局」之差就是这个单侧口径下
  # 的升级值。它跟全表的 Δ **不是一个口径**（这儿只量我方一侧、
  # 对手空装），所以**不能相减**，只拿来看方向对不对
  ( X=1 node tools/md-sim/proto-diag.js $k $ND 0 lock >"$TMP/a0_$k" 2>&1 ) &
  ( X=1 node tools/md-sim/proto-diag.js $k $ND 0 deepline >"$TMP/c0_$k" 2>&1 ) &
done
# 对照：映照单件（锚那一行自己的诊断）
( X=1 node tools/md-sim/proto-diag.js reflect $ND 0 lock >"$TMP/a_ANCHOR" 2>&1 ) &
( X=1 node tools/md-sim/proto-diag.js reflect $ND 0 deepline >"$TMP/c_ANCHOR" 2>&1 ) &
wait

scoreline() { grep -o '得分 [0-9.]*' "$1" | head -1; }
one() {
  echo "---- $2（$1）· 全表协同 A $3 / ♣ $4 ----"
  echo "  〔A 槽〕不挂映照 $(scoreline "$TMP/a0_$1")  →  挂上 $(scoreline "$TMP/a_$1")"
  # **那件技能自己的计数口也要打** —— 只打 reflect: 那行会漏掉要害。
  # 涌潮的 `over`（被顶过 13、彻底出界的张数）就是这么漏掉的，而
  # 「映照会不会把牌换成更高的脸、于是在涨水/涌潮下顶出界」这个问题
  # **只有那一格答得了**。挂映照前后各打一遍，比的是同一个计数
  echo "      不挂："; sed -n 's/^  /        /p' "$TMP/a0_$1"
  echo "      挂上："; sed -n 's/^  /        /p' "$TMP/a_$1"
  echo "  〔♣ 槽〕不挂映照 $(scoreline "$TMP/c0_$1")  →  挂上 $(scoreline "$TMP/c_$1")"
  echo "      不挂："; sed -n 's/^  /        /p' "$TMP/c0_$1"
  echo "      挂上："; sed -n 's/^  /        /p' "$TMP/c_$1"
  echo
}

echo "################ 对照：映照单件（锚） ################"
echo "  〔A 槽〕"; sed -e 's/^/    /' "$TMP/a_ANCHOR"
echo "  〔♣ 槽〕"; sed -e 's/^/    /' "$TMP/c_ANCHOR"
echo
echo "################ 升级档各件 ################"
for row in $ROWS; do
  k=${row%%:*}; rest=${row#*:}
  n=${rest%%:*}; rest=${rest#*:}
  sa=${rest%%:*}; sc=${rest#*:}
  one "$k" "$n" "$sa" "$sc"
done

echo "################ 怎么读 ################"
echo "〔kept + changed + noHand = fires，这是结构自检，对不上先查代码。"
echo
echo " changed / fires = **换脸率**。它才是「这件技能跟映照有没有真接触」："
echo "   ≈ 0      → 挑牌器在这件技能旁边恒选『不换』。那一行的协同 = -锚，"
echo "              是**盲区**不是结论 —— 这件技能的价值不走 catchStart。"
echo "   高且分涨 → 真协同（顺色 / 齐顶 / 磁钩 那一类，映照把『触发面』"
echo "              和『落堆面』拆开，用垃圾牌点槽、落好脸）。"
echo "   高而分跌 → 真冲突。注意**可选档的闸拦不住它**：闸问的是"
echo "              『收得多不多』，而亏在别的轴上，所以每次换脸都是"
echo "              一次无控交易。要修的是**闸的目标函数**，不是幅度。"
echo
echo " gainSum 只读『机制动没动』，**不读强度** —— 2026-10-21 已经栽过一次"
echo "（2.490/局 而得分只 +0.42，一张『多收的牌』兑现 0.17 分）。"
echo " 它的对照是『同一张牌不变』，而真对照是『换一张牌打』。〕"
