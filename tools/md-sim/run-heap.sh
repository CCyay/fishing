#!/bin/sh
# 【堆牌】机制的第一张矩阵〔2026-10-26 · 用户当天定的机制〕
#
# 机制原文：「带【堆牌】的牌打出后，从牌组取 2 张牌盖放在出牌者的堆牌区。
#   轮到自己的回合时，若自己的堆牌区有牌，则将这些牌打出到牌堆（跟推牌规则一样），
#   之后再是自己的出牌阶段。」
#
# ⚠ **口径 2026-10-28 改了**（用户当天四条）：关键词定成
#   **【堆牌N】= 给自己堆 N 张 / 【对方堆牌N】= 给对方堆 N 张**，
#   **「层」这个概念删掉了**（「堆牌 一次就是1张」），
#   牌库**不够 N 张就整笔不执行**（「比如 堆牌2，而牌组只有1张，则1张牌都不堆」）。
#   **默认档的行为逐位没变**，所以下面这一轮的数照旧可用 ——
#   `HEAP_N=2/4/6` 现在念「堆牌2 / 堆牌4 / 堆牌6」。
#   ⚠ 但这一轮的数是 **R4** 跑的，而现行规则档是 **R6**（张=分 / 抢牌 / TAIL=6）——
#   **跨规则档不能相减**，要现行的数得重跑。
#
# 载体是 `heap` —— **原型，不是待上架的技能**。它故意只有「自带【堆牌2】」
# 这一句，不配第二个效果，所以量出来的就是机制本身。
#
# ---- 这一轮要回答的那个问题 ----
#
# 【推牌】1 层单独量是 **−2.36**（实测）：R4 之下把堆推厚是喂给
# 「下一个匹配到的人」，而那个人通常是对手。【堆牌】是**延迟 + 自己先手**
# 的推牌 —— 厚起来的堆先交到自己手上。
# ⚠ 「所以它该是正的」是**设计推理，不是预测**。这一格一次都没量过，
#    别拿推牌那个 −2.36 去做减法（两件不同的机制，不是同一条线上的两档）。
#
# 口径：`cmdOne` 走 `measureBoth` —— **双方同角色、各插同一个槽、两侧都量**，
#   报的是 **X**（两侧平均）和 **D**（两侧之差的一半）。
#   槽 = 江口闸官 A 槽（`DEFAULT_ROLE='lock'` + `--slot 0`，都是默认值），不带常驻技。
#   **这一批可以直接跟全表（`all`）相减**；跟 `proto-diag` 那批单侧 `back` 不能。
#
# ⚠ **读数顺序是硬规矩**（诊断口先于分）：
#     `staged/fires`   该 ≈ 2。明显低 → 牌库闸卡住，看 `short`
#   → `flushes/fires`  该 ≈ 1。明显低 → 牌卡在区里到终局没落下去
#   → `hits/flushed`   撞点数按 0 点落的占比 = 这个机制的损耗面
#   → **最后才看分**。
#
# ⚠ 它**改局长**（牌从牌库取走、晚一个回合才落堆），所以这一格的口径
#   跟不动牌库的技能差一个牌库长度 —— 照【石涌】那条，别跨线相减。
cd "$(dirname "$0")/../.." || exit 1
N=${N:-20000}

run() {                       # run <标题> <环境前缀…>
  echo ""
  echo "============== $1 =============="
  shift
  # ⚠ **别收窄这个范围**〔2026-10-26 栽过〕：原先是 `1,14p`，而技能报表
  #   正好 14 行 —— 诊断标题卡在第 14 行，`staged/fires` 那几行一行都没出来，
  #   看上去像「诊断口是空的 = 机制没接上」。而这一批**最该先读的就是那几行**
  #   （脚本头上那条读数顺序）。24 行是报表 14 + 诊断 5 + 余量
  env "$@" node tools/md-sim/sim.js one heap -n "$N" 2>&1 | sed -n '1,24p'
}

# ① 主案 —— 每次取 2 张（用户给的数）
run "① 主案（HEAP_N=2，默认）"
# ② 取 4 张 —— 幅度那一维。偶数，奇偶照旧不变
run "② 取 4 张（HEAP_N=4）" HEAP_N=4
# ③ 取 6 张 —— 看它是不是单调（推牌那条线在 R4 下是**非单调**的）
run "③ 取 6 张（HEAP_N=6）" HEAP_N=6
# ④ 关掉「取不满一整层就不取」那道闸 —— 它是奇偶闸，这一格量的是
#    「残局多取那几张」值多少 + 奇偶被打乱的代价，**两样混着，只当方向读**
run "④ 不守奇偶闸（HEAP_SHORT=1）" HEAP_SHORT=1

# 对照：同一批的【推牌】。⚠ **不是「堆牌 − 推牌 = 延迟那一半」** ——
#   石涌那件带的是推牌 + 石化 + 钥匙，拿它当推牌的锚是错的。
#   现行表里单量推牌 1 层的那个 −2.36 是**对照组**跑出来的（不是 one 口径），
#   所以这儿先不放锚；真要锚得专门搭一件「只有推牌 1 层」的原型。
echo ""
echo "⚠ 这一批**没有同批锚** —— 见脚本里那段。定价要锚的话先补一件只带推牌的原型。"
