#!/bin/sh
# 打平档值 × 条件打法：第二批〔2026-10-22〕
#
# 第一批的结论：阶梯计分造不出「没有纯策略均衡」，但用户要的不是那个 ——
# 用户的原话是「**只要考虑要拿 2/3 档还是冒一点风险拿 4/5 档**」。
# 那只要**两边打平**（g1 = 0），`band.js` 解出来是 1 / 4 / 12。
#
# 这一批验两件事：
#
#   甲 打平是真的吗 —— 离线解出来的 g1=0 要在真跑里复现（分差 ≈ 0）
#      ⚠ 这是对**离线重算那套前提**的检验，不只是核一个数。
#        前提是「打法只认分档结构、不认档值」，真跑对不上就说明前提破了。
#
#   乙 **打平之后到底有没有决策** ——
#      打平只说明「一律忍」和「一律不忍」两套死板打法平手，
#      那也可能是「两套都一样烂、随便选」。真正要证的是：
#      **一套看牌面的条件打法能赢过这两套。**
#      手边现成的条件只有 HOLD_LEAD（领先 k 分就落袋为安，用户的事实 2），
#      它赢得了就说明牌面信息真的值钱 → 有决策。
#
# 读数：看每一行的「后手分差」。
#   甲：b 行该 ≈ 0（±2×se）
#   乙：c/d/e 行**显著 > 0** 才算有决策；全都 ≈ 0 = 条件也没用，得换条件
set -e
# ⚠ **这一行 2026-10-23 晚些补的，别删。** 当天 `HOLD_ONCE` / `HOLD_EV` /
#   `HOLD_BOTH` 三个旋钮的默认值全翻成了「开」，而这个脚本的每一段都是按
#   **翻之前的默认**写的（显式 `HOLD_ONCE=1` 才算开；`HOLD_BOTH` 不写 = 只给「你」）。
#   不钉住的话 b~e 四段会变成**两侧都忍** → 分差恒≈0，而 f 段
#  （`HOLD_BOTH=1` 的对称自检）会跟 b 段**逐字相同**，整组对照塌掉。
#   下面每一行的 `env X=1` 仍然覆盖这三个，所以本脚本的语义一个字没变。
#   〔2026-10-23 同日再补 `JACK_HOLD=0`：那个旋钮当天也从 0 翻成了 3
#     （用户拍板，见 ai.js 那一行）。**同一个坑的第二次** —— 不钉的话
#     本脚本每一段都变成「守 3 张闸的 AI」跑的，而它写的是「不守」〕
export HOLD_ONCE=0 HOLD_EV=0 HOLD_BOTH=0 JACK_HOLD=0
cd "$(dirname "$0")/../.."
N=${1:-20000}
S=tools/md-sim/sim.js
B=1,4,12

run() {
  echo ""
  echo "================ $1 ================"
  echo "        [$2]"
  env $2 node $S base -n "$N" 2>&1 | awk '
    /每人每局积分|后手分差/ { print; next }
    /忍 1 手诊断/ { on = 1 }
    on { print }
    /两边都不空|净值看分差/ { on = 0 }
  '
}

echo "#### 档值 $B —— band.js 离线解出的打平点（g1 = 0.00）"
run "a 双方贪心（盘子）"                "SCORE_BANDS=$B"
run "b 只有你忍 ← **甲：该 ≈ 0**"        "SCORE_BANDS=$B HOLD_ONCE=1"
run "c 只有你忍 + 领先 2 分就收手"        "SCORE_BANDS=$B HOLD_ONCE=1 HOLD_LEAD=2"
run "d 只有你忍 + 领先 5 分就收手"        "SCORE_BANDS=$B HOLD_ONCE=1 HOLD_LEAD=5"
run "e 只有你忍 + 领先 10 分就收手"       "SCORE_BANDS=$B HOLD_ONCE=1 HOLD_LEAD=10"
run "f 双方都忍（对称，自检该 ≈ 0）"      "SCORE_BANDS=$B HOLD_ONCE=1 HOLD_BOTH=1"

echo ""
echo "#### 判读：b ≈ 0 = 打平成立（离线那套前提也跟着验过了）。"
echo "####       c/d/e 里有显著 > 0 的 = **条件打法赢了两套死板打法 → 有决策**。"
echo "####       全 ≈ 0 = 比分不是有用的条件，换别的条件再试（手牌有没有备份匹配…）。"
