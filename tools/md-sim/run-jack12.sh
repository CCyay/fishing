#!/bin/sh
# **J 要不要留给厚堆** —— 验用户 2026-10-23 那句「给 J 加价…这样就不会用在 2/3 档」
#
# 为什么要专门量这一格：
#   `1,4,12` 定下来之后我报了一个数 —— J 有 **69.3%** 的次数是拿去收 2/3 张的
#   （双方贪心，20000 局）。双方都按 EV 忍也只压到 56.8%。
#   也就是说**光把档值抬高并不会把 J 从 2/3 档赶出去**，因为档值只改收成大小，
#   不改「这一手能不能配上」—— 而 J 通吃（`catchStart` 对 J 恒返回 0），
#   手里有 J 就永远有一张能匹配的牌，`bestCaught` 的 argmax 一定是它。
#
# 要把 J 赶出 2/3 档，得有一条**专门管 J 的判据**。而那条判据已经存在：
#   `JACK_HOLD=k` —— 堆不足 k 张就不打 J（2026-10-22 加的，默认关）。
#
# ⚠ **k 跟「档」是精确对应的**，不是近似：J 收 `堆 + 1` 张，所以
#     k=3 → 堆 ≥3 → 收 ≥4 → **J 再不会落进 2/3 档**（这就是用户那句话）
#     k=5 → 堆 ≥5 → 收 ≥6 → J 只落进 6+ 档
#   所以这一跑不是在「调参」，是在问**那条约束值不值**。
#
# ─────────────────────────────────────────────────────────────────────
# ⚠⚠ **这个脚本 2026-10-23 晚些整个重写过。原版在新默认下静默失效了。**
#
# 那天 `HOLD_ONCE` / `HOLD_EV` / `HOLD_BOTH` 三个旋钮全翻成了默认开，
# 而原版四段里**有三段不再是它注释说的那件事**：
#
#   | 原版那一段 | 它以为在量 | 翻默认之后实际在量 |
#   |---|---|---|
#   | 甲 对照 | 双方贪心 | **双方都会忍**（于是 69.3% 这个基准对不上） |
#   | 乙 JACK_HOLD=k | 只有你忍 J | **两侧都忍 J** → 分差必然≈0 |
#   | 丙 +HOLD_ONCE=1 | 只有你按 EV 忍 | **两侧**（它没写 HOLD_BOTH=0） |
#   | 丁 对称自检 | 丙的对称版 | **跟丙一模一样**，对照整个塌掉 |
#
#   最坏的是乙和丁：**它们会打出一排 ≈0 的分差**，而那个 0 读起来
#   完全像「守 J 不值钱」——真相是实验根本没做。
#   （台账第二节『R4 决策层定稿』那条公告点名的就是这个坑。）
#
# ⚠ **而且「赶得出去」和「值不值」要用两个不同的口径跑**，不能合并成一段：
#
#   · **赶得出去吗** → 看「按档汇总」的 `2/3 档 · 其中J`。那一行是**两人合计**，
#     所以这一问必须**对称**跑（两侧都守闸），不然只会掉一半，读成「没赶干净」。
#   · **值不值** → 看后手分差。分差是「你 − 庄家」，必须**不对称**跑
#     （`HOLD_BOTH=0`，只给你开），不然两侧同打法，分差恒≈0。
#
#   原版把两问塞进同一段，在旧默认（HOLD_BOTH 默认只有你）下
#   凑巧两边都能读；翻了默认之后两边同时坏掉。
# ─────────────────────────────────────────────────────────────────────
#
# ⚠ 计数口的坑（写在 ai.js:781）：`JACK_HOLD` 和 `HOLD_MIN` **共用 holdSkip
#   那一对计数**。这一跑不开 `HOLD_MIN`，所以「忍了 N 手」那一行在守闸段
#   纯是 J 的数；而同时开了 `HOLD_ONCE` 的段落走的是 `holdOnce` 另一对口，
#   两者不混（ai.js:919 vs 979 各写各的）。
set -e
# ⚠ **这一行是这一跑跑完之后补的，别删。** 这个脚本就是用来定 `JACK_HOLD`
#   的 k 的，而用户看完它的输出**当场把默认值从 0 定成了 3**
#   —— 于是它自己立刻变成了「按翻默认之前写的脚本」，跟那十个前辈一样。
#   不钉住的话坏三段，而且全是静默的：
#     · 甲0「纯贪心，JACK_HOLD **关**」→ 变成守 3 张闸，标题当场说谎；
#     · 甲1「减法的基准」→ 不再是台账 §三那张表的那一格；
#     · **丙0「减法的基准」→ 变成 k=3，于是「丙3 减丙0」恒 ≈0**，
#       整张第二问的表会读成「J 守闸一分不值」—— 跟真数（+2.16）反向。
#   下面每一段的 `env JACK_HOLD=$k` 仍然覆盖它，所以本脚本的语义一个字没变。
export JACK_HOLD=0
cd "$(dirname "$0")/../.."
N=${1:-20000}
S=tools/md-sim/sim.js

# `SCORE_BANDS` 不再传 —— `1,4,12` 2026-10-23 起是 rules.js 的默认值。
# 传了也对，但留着会让人以为它还是个实验参数。

pick() {
  awk '
    /按档汇总/ { c = 1 }
    c == 1 { print; if (/6\+ 档/) c = 0; next }
    /后手胜率|后手分差|先手时|后手时/ { print "    " $0; next }
    /忍了|算了|其中强制/ { print }
  '
}

echo "#########################################################"
echo "#  第一问：**赶得出去吗** —— 对称口径（两侧都守闸）"
echo "#  看「按档汇总」里 2/3 档那一行的『其中J』"
echo "#########################################################"

echo ""
echo "######## 甲0 纯贪心（两侧都不忍，JACK_HOLD 关） ########"
echo "〔历史基准：J 在 2/3 档 = 54712 次，占 J 全部的 69.3%〕"
env HOLD_ONCE=0 node $S base -n "$N" 2>&1 | pick

echo ""
echo "######## 甲1 现行默认（两侧按 EV 忍，JACK_HOLD 关） ########"
echo "〔**这一段才是减法的基准** —— 它就是 \`sim.js base\` 现在的样子〕"
node $S base -n "$N" 2>&1 | pick

for k in 2 3 4 5; do
  echo ""
  echo "######## 乙$k 现行默认 + JACK_HOLD=$k（**两侧**都守闸） ########"
  env JACK_HOLD=$k node $S base -n "$N" 2>&1 | pick
done

echo ""
echo "#########################################################"
echo "#  第二问：**值不值** —— 不对称口径（只给「你(后手)」开）"
echo "#  看后手分差。两段都写死 HOLD_BOTH=0，否则分差恒≈0"
echo "#########################################################"

echo ""
echo "######## 丙0 只有你按 EV 忍，不守 J（减法的基准） ########"
echo "〔台账记的 +0.90 就是这一段。跑出来对不上 +0.90 = 有别的东西变了，先查〕"
env HOLD_BOTH=0 HOLD_ONCE=1 HOLD_EV=1 node $S base -n "$N" 2>&1 | pick

for k in 2 3 4 5; do
  echo ""
  echo "######## 丙$k 只有你：按 EV 忍 + JACK_HOLD=$k ########"
  env HOLD_BOTH=0 HOLD_ONCE=1 HOLD_EV=1 JACK_HOLD=$k node $S base -n "$N" 2>&1 | pick
done

echo ""
echo "#### 怎么判："
echo "####   一、乙3 的「2/3 档 · 其中J」该掉到 ≈0（k=3 → 堆≥3 → 收≥4）。"
echo "####      不是 0 就**先查实现**，别改 k —— 说明有别的支绕过了那道闸。"
echo "####   二、**丙k 减丙0** = 「J 守闸」在会忍的 AI 之上还值几分。"
echo "####      ⚠ 减的是丙0（+0.90 那一段），**不是甲1、不是 base** ——"
echo "####      甲/乙是对称段，它们的分差恒≈0，拿去做减法会得出『守J白干』。"
echo "####   三、k 从 2 推到 5，丙段分差该有个峰。峰在哪决定 J 该守到几张。"
echo "####      ⚠ 没有峰（单调下行）= 用户那句话在这套规则下不成立，要报回去。"
echo "####   四、乙段还要看**积分和局长**：守 J 会把 J 压到后期，"
echo "####      局长不该变（出牌 23.0），变了说明闸改了牌的流向，不只是时机。"
