#!/bin/sh
# ============================================================================
#  〈dumpbait〉的**张数线**：1 / 2 / 3 / 任意〔2026-10-27 用户定要跑〕
# ============================================================================
#
#  起因：用户在给【对换】（R6 X=+5.75，超目标档位上限 5.5）找削弱形状时
#  提了「**把自己任意手牌给对方**」。那个效果模拟器里已经有 ——
#  原型〈dumpbait〉（`rules.js:1259`），**而它只量过「塞 1 张」那一格**。
#
#  ## 一、为什么这条线非量不可
#
#  `BAIT_N` 那条旋钮的注释里写着一句**没量过的假设**：
#    「塞的价值**很可能**跟换水一样对张数线性不递减」
#  而用户要的正是「任意张」—— 所以那句假设现在是这个设计的全部依据。
#
#  两边的实测参照（口径不同，别相减）：
#    换水 `SWAP_N` 2 张 **+1.22** → 任意张 **+1.74**（R3）  ← 自己洗回牌库，方向不同
#    倒饵 1 张                     **+1.29**（R6，这一轮刚跑）
#
#  ## 二、这一档真正的机制：不是「多塞几张」，是**他要花几手去清**
#
#  手牌 4 张是**下限**，`refill` 只补到下限、**上限不限**（CLAUDE.md 陷阱）。
#  所以塞 3 张废牌 ≠ 让他手牌变差 3 倍，而是 **他手里 7 张、其中 3 张要花 3 手清掉**。
#  这正是【死水】那条注释里的账：「废牌的真实代价是他要花几手去清」。
#
#  → 于是**局长口必读**：他多打 N 手 = 局面变长？还是 `refill` 抹平？
#    CLAUDE.md 陷阱①说手牌 ↔ 牌库之间的挪动被 refill 抹平，**可这一档是
#    手牌 ↔ 手牌**，不在那条豁免里。**基线 23.9 次/局**（R6 表一那个基线）。
#
#  ## 三、这件技能**不是下限**（罕见）
#
#  上一轮诊断口：`junk/given` 在 A 槽**精确 1.0000** —— 给出去的牌
#  本来就 100% 是他钓不着的，`BAIT_PICK` 三档因此几乎同值。
#  所以挑牌族那条「记成下限」的惯例**对这件不适用**（台账原文：
#  「它的低是真的低 —— 没有上升空间」）。
#  ⚠ 但那是 **1 张档**的花板。塞 2~3 张的时候手里不够废牌了，
#  `junk/given` 该从 1.0000 **掉下来** —— 那个掉幅就是「张数的真实上限」。
#  **这是这一跑最该盯的数，不是 X。**
#
#  ## 四、口径
#
#  `one` ≡ `all` ≡ `vs`（CLAUDE.md 第二节，实测逐位相同）——
#  所以这四格可以**直接跟《全技能速查》那一列相减**。
#  R6 = `SCORE_BANDS=off`（张=分）+ `STEAL_ON=1`（抢牌）+ `TAIL=6` + AI 按概率忍。
#  江口闸官 A 槽（4 张牌，定价锚槽）· 20000 局 · SE ≈ 0.15。
#
#  ⚠ ♥ 槽**没跑**：上一轮量到这件的槽型倍率 2.67×（A 1.45 → ♥ 3.87），
#  而全表 68 件全按 A 槽定价。张数线如果在 A 槽就顶到档位上限，
#  ♥ 槽会**再乘 2.67** —— 那一格要单独跑（`--role mirror --slot 0`）。
#
#  旋钮：N=局数 ND=诊断局数
set -u
N=${N:-20000}
ND=${ND:-4000}
cd "$(dirname "$0")/../.."

S="node tools/md-sim/sim.js one dumpbait -n $N"
D="node tools/md-sim/proto-diag.js dumpbait $ND 0 lock"
pick() { grep -E '后手 |胜率：|钓到'; }

echo "################ 0. 结构闸 ################"
node tools/md-sim/check.js >/tmp/dump-check 2>&1 && echo "check 过" || { cat /tmp/dump-check; exit 1; }

echo
echo "################ 1. 张数线（X / D / 胜率）################"
#
# ⚠ **两条臂，别只跑一条**〔2026-10-27 补〕：`BAIT_HOLD=1`（默认）是
#   「见好就收 = 你自己决定塞几张」，`BAIT_HOLD=0` 是「强制塞满 N 张」。
#   第一跑只跑了后者，于是 N=3 量出 **−0.75** 而我差点把它当成「任意张」的数 ——
#   实际带闸是 **+2.75**，**两条臂差 3.5 分**。
#   这正是 CLAUDE.md 那条：原型跟设计对不上的时候，那个数不是这个设计的数。
for k in 1 2 3 9; do
  for h in 1 0; do
    echo "---- BAIT_N=$k BAIT_HOLD=$h ----"
    BAIT_N=$k BAIT_HOLD=$h $S 2>&1 | pick
  done
done

echo
echo "################ 2. 诊断口（$ND 局）################"
cat <<'EOF'
〔**先读 `junk/given`，再读 X。**
   1 张档它精确 = 1.0000（给出去的全是他钓不着的）。塞 2~3 张的时候
   手里不够废牌了，它该掉下来 —— **那个掉幅就是张数的真实上限**。
 `given/fires` 该贴着 BAIT_N（贴不住 = 手牌不够，那也是上限）。
 `jack/given` 该贴 0 —— 把 J 塞给他是净送分。
 `turns` / 出牌次数：**基线 23.9**。这一档是手牌↔手牌，不吃 refill 那条豁免。〕
EOF
for k in 1 2 3 9; do
  for h in 1 0; do
    echo "---- BAIT_N=$k BAIT_HOLD=$h ----"
    BAIT_N=$k BAIT_HOLD=$h $D 2>&1 | grep -E 'dumpbait|出牌|turns'
  done
done

echo
echo "################ 3. 怎么读 ################"
cat <<'EOF'
一、`junk/given` 从 1.0000 掉下来的那一格 = **这条线的真实天花板**。
   X 还在涨而 junk 已经塌了，涨的就不是「塞废牌」，是「塞牌」本身
   （= 占他手牌位 / 逼他多打几手），**那是另一个机制，要分开记**。

二、**出牌次/局动了的话，X 里混着两件事**（手牌质量 / 局面长度），
   别合成一句「它变强了」。照台账那条：
   **一件技能改局长的时候，成本不在自己那一行，在全表那一列。**

三、⚠ **定价 / 命名 / 上不上架一个都没定** —— 这一跑只出数。
   〈dumpbait〉是 SIM_ONLY 原型（`refs.js` 登记着），用代号。

四、**2026-10-27 那一跑的八格结果不在这儿** —— 在 `rules.js` 的 `BAIT_N`
   注释里（那个旋钮自己的墓碑旁边），**别在这儿复制一遍**。
   一句话版：1 张 +1.29、2 张 +2.29、任意张（= 带闸 3 张）**+2.75**；
   不带闸的 3 张 **−0.75**（J 被迫送出去）。
EOF
