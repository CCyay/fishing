#!/bin/sh
# 【磁钩】换形状之后重量〔2026-10-26〕
#
# 用户定的新形状：「能匹配跟它相差 1 的牌」，而**映照那一句撤掉**
#（原话：「撤掉映照，只留新的匹配面」）。于是磁钩的三个旧数全废：
#   ~~+1.22 / +0.90~~（只匹配大 1）、~~+3.66~~（大 1 + 映照）、~~+1.26~~（更早一版）
# —— **三个都是别的形状的数，互相之间也不能相减**。
#
# 两档是为了把涨幅拆开：
#   `HOOK_DIR=both`（默认 = 现行形状）  相差 1，双向
#   `HOOK_DIR=up`                      只匹配大 1 —— 旧形状，**但在现行代码上**
#
# 所以 `both − up` 才是「双向」那一半值多少，而 `up` 那一格同时是一次
# 跨版本回归：它该跟台账里旧的「只匹配大 1」那个数在同一个 R 档下对得上。
# 对不上就说明这一轮碰坏了别的东西（`anyEquals(mine, theirs, gap)` 的语义是
# `theirs === mine + gap`，0 点牌的行为这一轮**故意没动**）。
#
# 价 50 是按旧的 +1.26 定的（25 + 1.26×21 = 51.5），**现在悬空** ——
# 量完由用户定价，不要自己改 `unlock`。
set -e
OUT=tools/md-sim
N=20000

# ---- ⚠⚠ 必须换槽：**A 槽量不出「相差 1」这个改动**〔2026-10-26 实测撞上的〕 ----
#
# `one` 默认插江口闸官第 1 槽 = **'A'**（`rules.js:3623` slots: ['A','2','3','4']）。
# 磁钩插 A 槽 = 只有打出 A（算 **1 点**）时生效，于是：
#
#   `+1` 支 → 匹配堆上 **2 点** 的牌  ← 真的有
#   `−1` 支 → 匹配堆上 **0 点** 的牌  ← **一局里根本不存在**
#              （0 点只能由死水 / 封竿 / 推牌撞点数 造出来，而这一跑双方只带磁钩）
#
# 所以新加的那一半在 A 槽里是**结构性空操作**。实测坐实了：A 槽 `both` 量出
# **X +0.90 / D +0.03**，跟旧的「只匹配大 1」那个 +0.90 **一模一样** ——
# 那不是 bug、也不是巧合，是**口径瞎了**。
#
# ⚠ 这跟【软点】是同一个坑（「A 本来算 1 点，插 A 是空操作」，它的真数在 '3' 槽）。
#   差别只在软点是**整件**空操作，磁钩是**半边**空操作 —— 后者更阴，
#   因为它照样给出一个像样的数（+0.90），不像 0.00 那样一眼可疑。
#
# 于是主跑换到 **'3' 槽（slot 2）**：'3' 的 ±1 两头（2 点和 4 点）都真实存在。
# ⚠ **换槽就换了标签，所以这两格不能跟全表 A 槽的数相减** ——
#   能减的只有同槽内部的 `both − up`（同一槽、同一批、同一版代码）。
SLOT=2

# ---- 计数口〔2026-10-26 补〕：`PROTO_STAT.hook` 的 up / down / both ----
#
# 加它的直接理由就是上面那个 A 槽坑：当时**没有计数口**，于是 +0.90
# 看着像个正常数，靠推才看出 −1 那一支一次都没点着。有了这一口，
# `down=0.000/局` 会自己打出来。
#
# ⚠ **这三个数的口径是「判定里命中过几次」，不是频次** —— 数的地方是
#   `catchStart`，而它被 AI 当探针反复试算（20 个调用点），绝对值被放大了。
#   所以只看两样：**零/非零**，以及 **up:down 之比**。
#   `both`（两头同时对得上）是重叠度 —— 它越大，「双向」的边际越小。
#   完整判据在 `rules.js` 的 `PROTO_STAT.hook` 那段注释里。
#
# ⚠ `proto-diag` 的第 4 个位置参数是槽号，**不传就是 A 槽** ——
#   不传等于把计数口也插进那个测不出的槽，`down` 必然是 0，
#   而那个 0 是口径产物不是结论。所以这儿必须带 $SLOT
DIAG=6000

for dir in both up; do
  echo "############ HOOK_DIR=$dir · '3' 槽（slot $SLOT）############"
  HOOK_DIR=$dir node $OUT/sim.js one hook -n $N --role lock --slot $SLOT \
    > $OUT/out-hook-$dir-s$SLOT.txt 2>&1
  grep -E 'X|D|标准误|口径' $OUT/out-hook-$dir-s$SLOT.txt | head -12
  echo "---- 计数口（$DIAG 局 · slot $SLOT）----"
  HOOK_DIR=$dir node $OUT/proto-diag.js hook $DIAG $SLOT \
    > $OUT/out-hook-diag-$dir-s$SLOT.txt 2>&1
  grep -E '分差|hook:' $OUT/out-hook-diag-$dir-s$SLOT.txt
  echo ""
done

# A 槽的计数口单独跑一次 —— 它是「A 槽测不出」那条判据的**直接证据**
#（预期：`up` 有数、`down` 贴着 0。`up` 也是 0 的话那是配装没装上，
#  整个脚本的数都不能用）
echo "############ 证据：A 槽的 down 该贴着 0 ############"
HOOK_DIR=both node $OUT/proto-diag.js hook $DIAG 0 \
  > $OUT/out-hook-diag-both-s0.txt 2>&1
grep -E '分差|hook:' $OUT/out-hook-diag-both-s0.txt
echo ""

# A 槽那两格照旧留着 —— 它是**上面那条判据的证据**（两档逐位相同 = 这个槽测不出），
# 而且 A 槽的 +0.90 本身仍然是「磁钩插 A 槽值多少」的真数，全表那一行用它
echo "############ 回归：A 槽两档该**逐位相同**（证明这个槽测不出） ############"
for dir in both up; do
  HOOK_DIR=$dir node $OUT/sim.js one hook -n $N > $OUT/out-hook-$dir-s0.txt 2>&1
done
diff $OUT/out-hook-both-s0.txt $OUT/out-hook-up-s0.txt \
  && echo "  ✓ 逐位相同 —— A 槽确实量不出「相差 1」（0 点牌不存在）" \
  || echo "  ✗ 有差异 —— 上面就是。那说明 A 槽**能**测出一点，上面那条判据要改"
