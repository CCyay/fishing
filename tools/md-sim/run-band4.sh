#!/bin/sh
# 第四批：**把 c 的窗口夹出来**〔2026-10-22〕
#
# 第三批 C 段量到的东西（20000 局、p=25%）：
#
#   档值      忍了      后手分差
#   1,4,12    0 手      −0.06（se 0.08）   ← 一次都没忍，这个 0 是空的
#   1,4,20    0.96 手   +0.50（se 0.13）
#   1,4,40    0.96 手   +2.61（se 0.25）
#   1,4,100   0.96 手   +8.93（se 0.61）
#   1,4,400   0.96 手   +40.54（se 2.44）
#
# 「忍了」从 c=20 起**一个数都不动**（0.96 / 升档 15.2% / 没升 76.5%，
# 四组逐位相同），因为折扣判据是个布尔开关，过了门槛就全开。
#
# 门槛是**算得出来的**，不用扫：判据 `later·p > now·100` 在 p=25 下就是
# `later > 4·now`，而逐个 N 代进去 ——
#
#   N=2/3  now=v0=1   later=scoreOf(4)=v1=4   4 > 4 假 → 永不忍
#   N=4/5  now=v1=4   later=scoreOf(6)=v2=c   c > 16  → 门槛在这儿
#   N≥6    now=later=v2                       假      → 不会再忍
#
# 所以**全部的忍都来自 N=4/5，而且 c > 4b 才会发生**。
# 这就是①的答案：存在那个 c，它等于 **b ÷ p**。
#
# 剩下的问题是窗口在哪：
#   c ≤ 16  → 一次不忍（决策是死的）
#   c = 20  → 忍得起来，但分差 +0.50（≈4σ）—— 忍**严格更优**，又成唯一解
#   中间    → 有没有一个 c 让「忍得起来」且「分差 ≈ 0」
#
# ⚠ 验收线在这一批收紧了：原来写的是**分差 ≥ 0**，不够 ——
#   +0.50 是 4σ 的正，那意味着忍严格压过贪心，还是「永远有最优解法」，
#   只是从「永远贪心」换成了「永远忍」。要的是 **|分差| 在 2σ 以内**
#   且 **忍了 > 0**。两条缺一条都不算。
set -e
# ⚠ **这一行 2026-10-23 晚些补的，别删。** 当天 `HOLD_ONCE` / `HOLD_EV` /
#   `HOLD_BOTH` 三个旋钮的默认值全翻成了「开」，而这个脚本是按**翻之前的默认**写的。
#   这儿还多一条：它用的是 `HOLD_P`，而 `HOLD_EV` 一旦默认开，
#   `HOLD_P` 所在的 `else if` **就到不了了** —— 设了什么都不会发生，静默。
#   另外 `HOLD_BOTH=1` 那几段的对照底（不写 HOLD_BOTH 的段）会跟它重合。
#   下面每一行的 `env X=1` 仍然覆盖这三个，所以本脚本的语义一个字没变。
#   〔2026-10-23 同日再补 `JACK_HOLD=0`：那个旋钮当天也从 0 翻成了 3
#     （用户拍板，见 ai.js 那一行）。**同一个坑的第二次** —— 不钉的话
#     本脚本每一段都变成「守 3 张闸的 AI」跑的，而它写的是「不守」〕
export HOLD_ONCE=0 HOLD_EV=0 HOLD_BOTH=0 JACK_HOLD=0
cd "$(dirname "$0")/../.."
N=${1:-20000}
S=tools/md-sim/sim.js

pick() {
  awk '
    /后手分差/ { print "      " $0; next }
    /忍了|期望值折扣改掉|其中/ { print }
  '
}

echo "######## 甲 夹窗口：b=4、p=25，c 从门槛 16 往上走 ########"
echo "〔c ≤ 16 不会忍，所以从 17 起。找 |分差| < 2σ 且忍了 > 0 的那一格〕"
for c in 16 17 18 19 20 22; do
  echo ""
  echo "==== 1,4,$c ===="
  env SCORE_BANDS=1,4,$c HOLD_ONCE=1 HOLD_P=25 node $S base -n "$N" 2>&1 | pick
done

echo ""
echo ""
echo "######## 乙 对称自检：双方都忍，分差该 ≈ 0 ########"
echo "〔这一格两侧同打法，分差显著不为 0 就是实现有问题，不是设计结论〕"
for c in 18 20; do
  echo ""
  echo "==== 1,4,$c · HOLD_BOTH=1 ===="
  env SCORE_BANDS=1,4,$c HOLD_ONCE=1 HOLD_P=25 HOLD_BOTH=1 node $S base -n "$N" 2>&1 | pick
done

echo ""
echo ""
echo "######## 丙 p 自洽吗：假设 25%，实测升档只有 15.2% ########"
echo "〔AI 按 25% 的成功率下注，而真跑出来只升档 15.2% —— 它太乐观了。"
echo "  p 调到 15 的话门槛变成 c > b÷0.15；这一段看调完之后实测升档率"
echo "  会不会跟 p 对上（对上 = 这套判据自洽，可以当定稿打法）〕"
for p in 15 20 25; do
  echo ""
  echo "==== 1,4,20 · HOLD_P=$p ===="
  env SCORE_BANDS=1,4,20 HOLD_ONCE=1 HOLD_P=$p node $S base -n "$N" 2>&1 | pick
done

echo ""
echo "#### 怎么判："
echo "####   甲 找 **忍了 > 0 且 |后手分差| < 2×se** 的那个 c —— 那是设计点。"
echo "####   乙 两格都该 ≈ 0。不为 0 = 实现有问题，甲的结论先别信。"
echo "####   丙 实测升档率跟 p 对得上的那一档 = 自洽的打法参数。"
