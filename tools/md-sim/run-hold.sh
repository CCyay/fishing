#!/usr/bin/env bash
# 2026-10-22 · 「养堆」到底有没有价值 —— 把用户那句观察拆成可证伪的两问
#
# ---- 这一跑要回答什么 ----
#
# 用户定的对照实验（原话）：
#
#   「**在一方有匹配就打，和一方养堆直到 3张/4张/5张 才收；
#     用这个来比较养堆难度**」
#
# 那正是 `HOLD_MIN` 的语义：这一手能收的最大张数 < k 就不收、改去下饵。
# 所以下面 `HOLD_MIN=3/4/5` 三档就是用户要的三格，对照组是「都贪心」。
#
# 起因是前一句观察：「**游戏决策性弱，能匹配就打不管收多少，没有养堆概念**」。
#
# `ai.js:pickCard` 的主循环**逐字就是那句话**：`bestCaught` 初值 0、
# 判据 `caught > bestCaught` —— 能收的都收、收得最多的优先，
# 没有任何一支问「堆才这么点，要不要先忍一手」。
#
# 但「AI 没这个概念」和「游戏没这个决策」是**两件事**，解法相反：
#
#   甲、**AI 笨** —— 规则里养堆有收益，只是一步贪心算不到。
#        那所有旧 X 都被系统性压着，是量法问题。
#   乙、**游戏真没这个决策** —— 忍一手在规则层就不划算。
#        那是设计问题，要加机制才有救。
#
# 这一跑就是用来分开它们的。
#
# ---- 口径 ----
#
# `cmdBase`：双方空槽、`freeFirst: true`（切牌定庄，两侧先手概率相同），
# 所以「你(后手)」和「庄家(先手)」两列是一组**干净的 A/B** ——
# 没有先后手偏差要扣，不像别的命令要减那 +0.31。
#
# 旋钮**默认只给「你」那一侧开**（`ai.js` 的 `holdSide`），于是
#「后手分差（你 − 庄家）」那一行直接就是养堆的价值。
#
# ⚠ **对照组那一行必须跟着这一跑一起出**，不能引旧的 —— 这一版
#   动过 `rules.js`（加了 `jackTook` 计数），而 CLAUDE.md 那条：
#   两个数不一样时先查是不是同一版代码。
#
# ---- 诊断口（CLAUDE.md 第四节）----
#
# 「J 每次吃几张」是这一跑的机制诊断口，**不是 X**。
# `JACK_HOLD=k` 开了之后它要是纹丝不动，说明那道闸根本没咬上
#（堆本来就够厚），那一行的分差就不能当养堆的价值读 ——
# 照同色闸那次：X 4.89 / 修好 4.88，光看 X 永远发现不了机制没接上。
set -u
# ⚠ **这一行 2026-10-23 晚些补的，别删。** 当天 `HOLD_ONCE` / `HOLD_EV` /
#   `HOLD_BOTH` 三个旋钮的默认值全翻成了「开」，而这个脚本是按**翻之前的默认**写的
#   —— 它下面那句「旋钮只给「你」那一侧开」靠的就是 `HOLD_BOTH` 不写 = 只给 ME。
#   不钉住的话 j2~j6 / m3~m5 九档全变成**两侧对称**，分差恒≈0，
#   而第①节那张表的判据正是「分差显著不显著」—— 九档会齐刷刷读成「养堆白干」。
#   `run ctl HOLD_NONE=1` 那一行的对照组不受影响（HOLD_NONE 是另一把总闸）。
#   下面 `run` 传进去的 `env X=k` 仍然覆盖这三个，所以本脚本的语义一个字没变。
#   〔2026-10-23 同日再补 `JACK_HOLD=0`：那个旋钮当天也从 0 翻成了 3
#     （用户拍板，见 ai.js 那一行）。**同一个坑的第二次**，而这儿坏的是
#     `ctl` 和 m3~m5 四档 —— 它们不写 JACK_HOLD，会变成「守 3 张闸」跑的，
#     于是 ①那张表的对照组不再是「都贪心」。j2~j6 的 `env JACK_HOLD=k` 照旧覆盖〕
export HOLD_ONCE=0 HOLD_EV=0 HOLD_BOTH=0 JACK_HOLD=0
N=${N:-20000}
cd "$(dirname "$0")/../.."
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

# 「后手分差（你 − 庄家）：+0.31 分（标准误 0.12）」→ 「0.31 0.12」
#
# ⚠ 用 sed 不用 awk：那一行里 `你 − 庄家` 的减号**两边都有空格**，
#   按空白切字段的话 `庄家）：+0.31` 会黏成一个字段，字段号没法稳定数。
#   正则照着真输出写（sim.js:441 那两行 console.log）
diff2() {
  sed -nE 's/.*后手分差.*：\+?(-?[0-9.]+) 分（标准误 ([0-9.]+)）.*/\1 \2/p' "$1" | head -1
}
# 表里某一行的前两列（你 / 庄家）。标签不带空格的行才能这么取 ——
# 「J通吃占所有钓牌」那种带空格的要先数一位，所以这儿只喂无空格标签
col2() { awk -v K="$1" '$1 == K {print $2, $3; exit}' "$2"; }
# 「每人每局积分」「每人每局出牌」「每次平均收」也都不带空格
row() { col2 "$1" "$2"; }

run() { # $1 = 标签, 其余 = 环境变量赋值
  local tag="$1"; shift
  env "$@" node tools/md-sim/sim.js base -n "$N" >"$TMP/$tag" 2>&1
}

# ⚠ 这一行**别用反引号**写 base —— 双引号里的反引号是命令替换，
#   会去执行 `base` 然后报 command not found
echo "局数 $N · 每格一跑，base 口径（自由先手），旋钮只给「你」那一侧开"
echo

# 对照 + JACK_HOLD 扫一遍 + HOLD_MIN 扫一遍
run ctl HOLD_NONE=1 &
for k in 2 3 4 5 6; do run "j$k" JACK_HOLD="$k" & done
for k in 3 4 5; do run "m$k" HOLD_MIN="$k" & done
wait

echo "################ ① 分差（你 − 庄家）= 养堆的价值 ################"
echo "〔对照那一行该在 0 附近 —— 两边打法相同。判显著要 |分差| > 2×标准误〕"
echo
printf "   %-14s %8s %8s   %s\n" "档" "分差" "标准误" "判读"
for f in ctl j2 j3 j4 j5 j6 m3 m4 m5; do
  case $f in
    ctl) name="对照（都贪心）" ;;
    j*)  name="JACK_HOLD=${f#j}" ;;
    m*)  name="HOLD_MIN=${f#m}" ;;
  esac
  got=$(diff2 "$TMP/$f")
  if [ -z "${got:-}" ]; then
    echo "   $name  ⚠ 没抓到 —— 下面贴原文"
    cat "$TMP/$f"
    continue
  fi
  set -- $got
  awk -v NAME="$name" -v D="$1" -v E="$2" 'BEGIN{
    a = D < 0 ? -D : D
    if (a > 2 * E) { tag = (D > 0 ? "✅ 显著为正 = 养堆有赚" : "✅ 显著为负 = 忍是亏的") }
    else { tag = "— 不显著" }
    printf "   %-14s %8.2f %8.2f   %s\n", NAME, D, E, tag
  }'
done

echo
echo "################ ② 忍了几手 · 放弃了多少 ################"
echo "〔**这一节跟①一样重要**：「忍 2 次换一个大的」和「忍 12 次换一个"
echo "  大的」能得出同一个分差，而两者对设计的含义相反 ——"
echo "  前者是可玩的张力，后者是枯等。"
echo "  「合计放弃」是**账面成本**，①那个分差是**净值**，"
echo "  两者的差就是养堆真正赚回来的那部分〕"
echo
for f in j2 j3 j4 j5 j6 m3 m4 m5; do
  case $f in
    j*) name="JACK_HOLD=${f#j}" ;;
    m*) name="HOLD_MIN=${f#m}" ;;
  esac
  line=$(grep -m1 '忍了' "$TMP/$f" || true)
  if [ -z "${line:-}" ]; then
    echo "   $name   ⚠ 一次都没忍 —— 闸没咬上，①那一行不能当养堆的价值读"
  else
    echo "   $name   ${line#    }"
  fi
done

echo
echo "################ ③ 那道闸咬上了没有（另一个角度） ################"
echo "〔「J每次吃几张」两列要**拉开**才说明 JACK_HOLD 真生效了。"
echo "  纹丝不动 = 堆本来就够厚，闸没咬上，①那一行不能当养堆的价值读〕"
echo
printf "   %-14s %13s %13s %13s %13s\n" "档" "J每次吃几张" "每次平均收" "每人每局钓到" "每人每局积分"
for f in ctl j2 j3 j4 j5 j6 m3 m4 m5; do
  case $f in
    ctl) name="对照（都贪心）" ;;
    j*)  name="JACK_HOLD=${f#j}" ;;
    m*)  name="HOLD_MIN=${f#m}" ;;
  esac
  jt=$(row "J每次吃几张" "$TMP/$f")
  av=$(row "每次平均收"   "$TMP/$f")
  ct=$(row "每人每局钓到" "$TMP/$f")
  sc=$(row "每人每局积分" "$TMP/$f")
  printf "   %-14s %13s %13s %13s %13s\n" "$name" "${jt:-⚠}" "${av:-⚠}" "${ct:-⚠}" "${sc:-⚠}"
done
echo "  〔每格两个数 = 你 / 庄家〕"
echo "  〔「每人每局出牌」恒 23.0 两侧，已知不动，这一轮腾出位子给积分〕"
echo
echo "  ⚠ **②的「合计放弃」是账面，这儿的积分才是净值。**"
echo "    两者的差 = 养堆后来真赚回来的那部分；而「你跌多少」和"
echo "    「庄家涨多少」要分开看 —— 前者是你自己的净亏，"
echo "    后者是**你喂给对手的那部分**（你忍的时候他照收）。"
echo "    ①那个分差是两者之和，所以它**高估了养堆本身的亏损**。"

echo
echo "################ 原文（对照 + JACK_HOLD=4） ################"
cat "$TMP/ctl"
echo
echo "---- JACK_HOLD=4 ----"
cat "$TMP/j4"
