#!/usr/bin/env bash
# 2026-10-21 · 验一件事：**full 档「翻几张」为什么不等于 CAP**
#
# 主诊断跑出来 full·4 翻 3.60、full·6 翻 5.23 —— 都比 CAP 少约 10~13%。
# 按项目规矩这一格**不查清楚不能往下读**（同色闸那次 bug 下 X 4.89 /
# 修好 4.88，只看 X 永远发现不了；而「看着合理的数」正是那一类）。
#
# ---- 查代码得到的解释 ----
#
# `floodFor` 里 `fd.fires[side]++` 在 **while 循环之前**，而
# `fd.flipSum[side] += flipped` 在之后 —— 所以**牌库已空那几手的
# `flipped = 0` 也被算进了平均**。局末牌库必然耗尽（终局规则就是
# 「牌库空 + 双方合计再打 2 手 = 各 1 手」），所以欠缺是构造出来的，不是闸写错了。
# 〔2026-10-23 更正：这儿原先抄的是 `ruleTag()` 印的「各再打 2 手」，
#   而那句话把一个**合计量**插进了「各」的句式，整整多了一倍。已修 `rules.js`。
#   这条论证本身不受影响 —— 它只要「局末必然有几手牌库是空的」〕
#
# ---- 但推理不是证据。这个解释有一个可证伪的预测 ----
#
#   **欠缺率（1 − 翻几张/CAP）该随 CAP 单调递增**，而且小 CAP 下趋近 0：
#   推得越多 → 牌库空得越早 → 越多手撞上空库。
#
#   反过来，如果欠缺率在各 CAP 下**大体是个常数**（比如一律 10%），
#   那就不是牌库见底，而是循环的闸每次都少跑一轮 —— 那是 bug。
#
# 这一跑把 full 档的 CAP 扫全，就是为了把这两种解释分开。
set -u
N=${N:-20000}
cd "$(dirname "$0")/../.."
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

for c in 2 3 4 5 6 8; do
  ( FLOOD_STOP=full FLOOD_CAP=$c node tools/md-sim/sim.js vs flood flood \
      -n "$N" --role lock --slot 0 >"$TMP/f$c" 2>&1 ) &
done
wait

echo "################ full 档：翻几张 vs CAP ################"
echo "   CAP    后手翻   先手翻   两侧均   欠缺      欠缺率"
for c in 2 3 4 5 6 8; do
  awk -v C="$c" '
    /^    后手（我）/   { me = $4 }
    /^    先手（对手）/ { foe = $4 }
    END {
      if (me == "" || foe == "") { printf "   %-5s （没抓到）\n", C; exit }
      avg = (me + foe) / 2
      printf "   %-5s %7.2f %8.2f %8.2f %8.2f %9.1f%%\n",
        C, me, foe, avg, C - avg, (C - avg) / C * 100
    }
  ' "$TMP/f$c"
done

echo
echo "################ 怎么判 ################"
echo '〔**欠缺率单调递增、而且 CAP=2 那格明显最小** → 牌库见底，闸是对的。'
echo ' **欠缺率各档大体是个常数** → 循环每次少跑一轮，是 bug，整批数作废。'
echo
echo ' 注意看的是「欠缺率」那一列，不是「欠缺」那一列 —— 绝对欠缺'
echo ' 本来就会随 CAP 涨，它区分不开这两种解释。〕'
