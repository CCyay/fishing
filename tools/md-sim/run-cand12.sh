#!/bin/sh
# 候选档值 **1,4,12** 的正面对打〔2026-10-23〕
#
# 来自第五批的两条实测（R3、20000 局、补完 HOLD_PEN 漏之后）：
#   · b/a = 4  → 情况 3·牌组厚 判忍 30.0%、牌组薄 2.3%（分得最开的一格）
#   · c/b = 3  → 4/5 档起（4→6）判忍 17%（戊段四格平到小数点后一位）
#
# 这一跑要回答两件事：
#   一、**贪心 和 按计算忍 正面打，谁赢** —— 乙段就是那一格
#       （我这侧按 EV 忍，对手纯贪心，两侧其余逻辑完全相同）
#   二、**12 档（收 ≥6 张）到底出不出得来、占多少分**
#       —— 用户说它该「加更多但基本无法拿到」，这一跑验那个「基本无法」
#
# ⚠ 甲乙丙三段的**档值完全相同**，差别只在谁会忍。所以三段的
#   「收 N 张曲线」可以直接相减 —— 同一版代码、同一组档值、同一个口径。
set -e
# ⚠ **这一行 2026-10-23 晚些补的，别删。** 当天 `HOLD_ONCE` / `HOLD_EV` /
#   `HOLD_BOTH` 三个旋钮的默认值全翻成了「开」，而这个脚本是按**翻之前的默认**写的。
#   不钉住的话：第一段（「HOLD_ONCE 不开」）会变成**开着**，
#   第二段变成两侧，于是跟第三段（`HOLD_BOTH=1`）逐字相同 —— 三段塌成一段。
#   下面每一行的 `env X=1` 仍然覆盖这三个，所以本脚本的语义一个字没变。
#   〔2026-10-23 同日再补 `JACK_HOLD=0`：那个旋钮当天也从 0 翻成了 3
#     （用户拍板，见 ai.js 那一行）。**同一个坑的第二次** —— 不钉的话
#     本脚本每一段都变成「守 3 张闸的 AI」跑的，而它写的是「不守」〕
export HOLD_ONCE=0 HOLD_EV=0 HOLD_BOTH=0 JACK_HOLD=0
cd "$(dirname "$0")/../.."
N=${1:-20000}
S=tools/md-sim/sim.js
B=1,4,12

# 胜率 / 分差 / 忍的诊断 / 收 N 张整张表，都要。
# 收 N 张那一段用**区间**取（从标题到「出牌时堆有多厚」的数据行），
# 不逐行配格式 —— 表格的列宽是 padStart 拼的，照着写正则早晚对不上
pick() {
  awk '
    /收 N 张的难度曲线/ { c = 1 }
    c == 1 {
      print
      if (seen && /^   [0-9]+ [0-9]/) { c = 0; seen = 0 }
      if (/出牌时堆有多厚/) seen = 1
      next
    }
    /后手胜率|后手分差|先手时|后手时|先后手价差/ { print "    " $0; next }
    /忍了|算了|外面还剩|档起|情况 3|其中/ { print }
  '
}

echo "################ 甲 双方贪心（谁都不忍）—— 这是对照底 ################"
echo "〔1,4,12，但 HOLD_ONCE 不开。注意它**不等于 base**："
echo "  base 是 SCORE_BANDS 没设（积分 = 张数）。这一格换了档值但没人忍，"
echo "  所以它才是乙段唯一正确的减法对象。〕"
env SCORE_BANDS=$B node $S base -n "$N" 2>&1 | pick

echo ""
echo ""
echo "########## 乙 **我按计算忍 vs 对手贪心** ←这就是用户要的对打 ##########"
echo "〔两侧其余逻辑一个字不差，差别只有「我会按 EV 忍、他不会」。"
echo "  所以胜率和分差相对甲段的变化，**全部**是「按计算忍」这件事带来的。〕"
env SCORE_BANDS=$B HOLD_ONCE=1 HOLD_EV=1 node $S base -n "$N" 2>&1 | pick

echo ""
echo ""
echo "################ 丙 双方都按计算忍（对称自检）################"
echo "〔两侧同打法，后手分差该回到基线那个量级（−0.07 上下）。"
echo "  回不去 = 实现不对称，乙段的结论先别信。"
echo "  另外这一格的「收 N 张曲线」才是**双方都会忍的世界**长什么样 ——"
echo "  12 档的真实出现率要看这一格，不是看乙段（乙段对手不养堆）。〕"
env SCORE_BANDS=$B HOLD_ONCE=1 HOLD_EV=1 HOLD_BOTH=1 node $S base -n "$N" 2>&1 | pick

echo ""
echo "#### 怎么读："
echo "####   一、乙段的「后手胜率」减甲段的 = **按计算忍换来几个百分点**。"
echo "####      注意这是**后手**胜率，基线本来就不是 50%（R3 基线 48.1%）——"
echo "####      所以要看的是**差**，不是绝对值。"
echo "####   二、12 档出现率看每段「收 N 张」表里 N≥6 那几行的「次数」和"
echo "####      「占总分」。用户要的是「加更多但基本无法拿到」——"
echo "####      **占总分太高就说明它没在画饼，而是真能拿到**，那 c 得压。"
echo "####   三、甲→丙 的 N≥6 次数变化 = 养堆这件事把牌堆推厚了多少。"
