#!/bin/sh
# ============================================================================
#  【滤饵】抽 N 洗 N−1 —— 一条线上六格，一次量全〔2026-10-22 用户点的形状〕
# ============================================================================
#
#  用户原话：「抽 N 洗 n−1，你给数据我看哪个还是，都列出来」
#  —— 所以这一跑**不选形状**，它只负责把一条线上的六格全摊开。
#
#  ## 为什么这条线比我原先那两格干净
#
#  我原先量的是「抽 1 洗 1」和「抽 2 洗 1」，而那**两格在两个维度上同时不同**
#  （看几张 / 有没有盲补），所以它们之间那 0.11~0.29 分不能归给任何一个
#  （照 10-21 洪水那条教训的第三层：对照组只能证伪它量的那一个维度）。
#
#  **抽 N 洗 N−1 把第二个维度消掉了。** 按一整个回合算：
#
#    手牌：−1（打出）+N（抽）−(N−1)（退） = **0** → 停在 4 张
#          → 手牌 4 张是**下限**、`refill` 只补到下限 → **`refill` 空转，全档都不盲补**
#    牌库：−N +(N−1) = **−1** → 跟普通一手一样 → **全档局长中性**
#
#  于是六格之间**只差一个变量：看几张**。这一条线上的数可以互相相减。
#  （⚠ 跟上一跑那两格**不能**相减 —— 那两格有一个带盲补。）
#
#  语义上它是「**`refill` 那一张从盲摸变成 N 选 1**」：手里 3 张 + 抽 N 张，
#  留下最好的 4 张。N=1 退化成 refill 自己。
#
#  ## N=1（抽 1 洗 0）是**自检格，不是候选形状**
#
#  打完手里 3 张 → 抽 1 → 4 张 → 退 0 → `refill` 不补。
#  而不带这件技能时：3 张 → `refill` 摸 1 张 → 4 张。**两条路该是同一件事。**
#
#    → **这一格该贴着 0.00。** 不是 0 的话，说明 `drawFor` 和 `refill` 在某处
#      不等价（最可能是并行数组 `seen` 那一侧：`drawFor` 自己 push `seen`），
#      而**那本身是要查的东西**，不是这条线的数据。
#
#  ## 读数：这条线上 `fromDrawn/returned` **不是机制口了**
#
#  ⚠ 上一跑那两格的机制口是 `fromDrawn/returned`（退回去的里有几张是刚抽的），
#    **而它在这条线上被算术顶着往上走，不能当机制口用**：
#
#      退 N−1 张，而原手牌只有 3 张能退
#        → 刚抽的那几张至少要退 (N−1)−3 张
#        → `fromDrawn/returned ≥ (N−4)/(N−1)`
#      N=5 时下限已经是 0.25，N=6 是 0.40 —— **涨上去不代表「白抽」。**
#
#  **这条线的机制口要自己算一下，分母是 3：**
#
#      原手牌被换掉几张 = (`returned` − `fromDrawn`) / 局，上限 3
#        贴 0   → 抽上来的全比手里差，这件只是个「N 选 1 的 refill」
#        贴 3   → 手里三张全被换掉了 = 过滤到底，**再加 N 也没用了**
#      这一格饱和在哪儿，就是这条线该停在哪儿。
#
#  另两个口照旧：
#      `drawn/fires`    低于 N = 撞上牌库见底。**大 N 必然撞**，要看撞多狠
#      `returned/fires` 该贴着 N−1（手牌空了退不动 → 低于它）
#
#  ## ⚠ 大 N 撞上牌库见底的时候，这件技能**变成另一件技能**
#
#  抽牌那个循环 `drawFor` 返 null 就 `break`，**而退牌那个循环照旧退满 N−1 张**
#  （它只在手牌空了才停）。于是牌库剩 2 张、N=6 的那一手：
#
#      抽到 2 张 → 手里 5 张 → 退 5 张 → 手里 **0 张** → 退回去的 5 张进了牌库
#        → `refill` 再从那 5 张里盲摸 4 张回来
#
#  **那已经不是「N 选 1 的 refill」了，是「把手牌搅回牌库重摸」**，
#  而且**盲补回来了**（这条线本来的卖点就是没有盲补）。
#
#  → 所以 `drawn/fires` 掉得越多，**那一格的 X 里混进来的就越不是这个机制**。
#    判法：`returned/fires` 贴着 N−1 而 `drawn/fires` 明显低于 N，**两者的差就是搅动量**。
#    ⚠ 这不是「截断」（截断只是少抽几张、效果变小），是**换了机制**，
#      所以大 N 那几格要是翘起来或者塌下去，先查这一格再谈设计。
#
#  ## 口径
#
#  `vs X X` 同件传两次 = 「先手 vs 后手」那个特例，打两侧原始值。
#  **X = 两侧平均、D = 差的一半**（CLAUDE.md 第二节：`one` ≡ `all` ≡ `vs`，
#  所以这么算出来的 X 可以直接跟《全技能速查》那一列比）。
#  参照（同口径、不同跑）：**换水 A 槽 X 1.73**（速查表）/ **1.75**（10-22 那跑）。
#
#  ⚠ 这一跑**不带 `all`** —— `vs` 已经给出同口径的 X / D，而上一跑那个
#    `all -n 8000` 比速查表那列（20000）se 大，加它只会多一个不能相减的数。
#
#  ## 闸
#
#  **代码跟 `check.js` 九组全过那一跑是同一版（没动过一个字）**，所以默认跳过结构闸。
#  要跑就 `GATE=1`。
#
#  旋钮：N=局数 ND=诊断局数 J=并发 NMAX=量到抽几张
set -u
N=${N:-20000}
ND=${ND:-4000}
NMAX=${NMAX:-6}
J=${J:-$(nproc 2>/dev/null || echo 8)}
cd "$(dirname "$0")/../.."
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

pick() {
  grep -E '手里：|先手 − 后手|镜像协同' | head -4 \
    | sed -e 's/^ *//' -e 's/标准误/se/'
}
job() {
  local tag=$1; shift
  while [ "$(jobs -rp | wc -l)" -ge "$J" ]; do wait -n 2>/dev/null || break; done
  ( env "$@" >"$TMP/$tag" 2>&1 ) &
}
show() { echo "-- $2"; [ -f "$TMP/$1" ] && cat "$TMP/$1" | pick; }

if [ "${GATE:-0}" = "1" ]; then
  echo "################ 0. 结构闸 ################"
  node tools/md-sim/check.js >"$TMP/check" 2>&1; rc=$?
  node tools/md-sim/refs.js  >"$TMP/refs"  2>&1; rc2=$?
  if [ $rc -ne 0 ] || [ $rc2 -ne 0 ]; then
    cat "$TMP/check"; echo; cat "$TMP/refs"
    echo "!!!! 结构没过（check=$rc refs=$rc2）—— 停。"
    echo "     ⚠ 这一跑一行代码都没改，所以断了的话**不是这一跑弄的**。"
    echo "     查法：对着断点那一手的七个桶，找「谁 −1 了而谁没 +1」。"
    exit 1
  fi
  echo "全过。"
fi

V="node tools/md-sim/sim.js vs"
A="--role lock --slot 0"        # A 槽：点数、4 张（窄）= 定价锚槽
H="--role mirror --slot 0"      # ♥ 槽：花色、13 张（宽）

n=1
while [ "$n" -le "$NMAX" ]; do
  b=$((n - 1))
  job "a$n" SIFT_DRAW=$n SIFT_BACK=$b $V sift sift -n $N $A
  job "h$n" SIFT_DRAW=$n SIFT_BACK=$b $V sift sift -n $N $H
  job "d$n" SIFT_DRAW=$n SIFT_BACK=$b \
    node tools/md-sim/proto-diag.js sift $ND 0 lock
  n=$((n + 1))
done
wait

echo
echo "################ 1. 抽 N 洗 N−1 · A 槽（定价锚槽）################"
n=1
while [ "$n" -le "$NMAX" ]; do
  if [ "$n" = "1" ]; then
    show "a$n" "抽 1 洗 0 ← **自检格**：该贴着 0.00（= refill 自己）"
  else
    show "a$n" "抽 $n 洗 $((n - 1))"
  fi
  n=$((n + 1))
done

echo
echo "################ 2. 抽 N 洗 N−1 · ♥ 槽（宽槽）################"
n=1
while [ "$n" -le "$NMAX" ]; do
  show "h$n" "抽 $n 洗 $((n - 1))"
  n=$((n + 1))
done

echo
echo "################ 3. 诊断口（$ND 局 · A 槽）################"
# ⚠ 这一段**必须用引号 heredoc** —— 里面有反引号，`echo "..."` 会当成命令替换
#   （这是这个会话里反复踩的那个坑）
cat <<'EOF'
〔机制口要自己算：**(returned − fromDrawn) = 原手牌被换掉几张，上限 3**。
  `fromDrawn/returned` 在这条线上被算术顶着涨（≥ (N−4)/(N−1)），**别拿它当机制口**。
  `drawn` 低于 N = 牌库见底；`returned` 该贴 N−1。
  还要看第一行那个「我方出牌 N 次/局」—— **六格该全等于 23.0**，
  那是局长中性那笔账（手牌净 0 / 牌库净 −1）唯一的验法。〕
EOF
n=1
while [ "$n" -le "$NMAX" ]; do
  echo
  echo "---- 抽 $n 洗 $((n - 1)) ----"
  [ -f "$TMP/d$n" ] && grep -E '出牌|sift:' "$TMP/d$n"
  n=$((n + 1))
done

echo
echo "################ 4. 怎么挑 ################"
cat <<'EOF'
一、X = 两侧平均、D = 差的一半（`vs` 打的是两侧原始值，**那个差不是 D**）。
   同口径的参照：**换水 A 槽 1.73**（速查表 20000 局）。

二、**这六格之间可以相减**（只差「看几张」一个变量），
   **但不能跟上一跑的「抽 1 洗 1 / 抽 2 洗 1」相减** —— 那两格带盲补。

三、挑的判据不是「哪个最高」，是**边际值在哪儿塌下来**：
   看 ΔX（N → N+1）和「原手牌被换掉几张」那一格一起饱和在哪儿。
   饱和之后再加 N 只是在吃牌库见底，不是在加强度。

四、⚠ **定价、命名、上不上架都没定** —— 这一跑只出数。
EOF
