#!/bin/sh
# 【撒网】的形状矩阵：量「奇偶」这个轴的幅度分布〔2026-10-20〕
#
# 为什么要跑它：`draw-skills.uts` 那条注释把**散收版**判死了
#（「奇偶面本来就太大了，那也是它当初卖 160 还不给升级的原因」），
# 而**那句话底下没有数** —— 160 是升级制时代的定价推理，按真相层级
# 那是「印象」那一层。而连续段版实测只有 **+2.51**，**低于目标档
# 2.7 的下限**。所以「奇偶面太大」这个前提本身要重新量。
#
# 口径 `vs cast cast`：默认 role=lock（江口闸官）、slot=0（A，4 张）、
# 不带常驻技、n=20000 —— **跟台账那张 `all` 全表一字不差**，
# 所以每一格都能直接跟撒网那一行的 +2.51 相减。
#
# 八格：
#   seg      连续段（= 现行 `desc`，**这一格是零点**）
#   all      散收（旧形状）
#   segpick  连续段 + 奇偶自选
#   allpick  散收  + 奇偶自选（原版钓鱼的形状）
#   segopp   连续段 · 固定收**异**奇偶（它自己保底收走）
#   allopp   散收   · 固定收**异**奇偶
#   rev      【逆网】原型：从**堆底**起连续（撒网的镜像）
#   miss     【错潮】原型：它下面那张异奇偶时才发动，发动就散收同奇偶的
#
# ⚠ 后四档**跟现行 `desc` 不符** —— 它们是**另几件技能的原型**，
# 量出来的数不能当撒网的数。自选那两档量的是「如果当初没撤掉那次选择」。
#
# 结果（2026-10-20，八格全跑完）在台账『奇偶这条轴量全了』那一节：
# seg +2.51 / all +2.89 / segpick +3.57 / allpick +3.20 /
# segopp +0.44 / allopp +0.42 / rev +1.15 / miss −0.29，|D| 全 ≤ 0.05。
N=${N:-20000}
for m in seg all segpick allpick segopp allopp rev miss; do
  echo "######## CAST_MODE=$m ########"
  CAST_MODE=$m node tools/md-sim/sim.js vs cast cast --n "$N" 2>&1 \
    | grep -E "手里|先手 − 后手|撒网·|打出次数"
  echo
done
