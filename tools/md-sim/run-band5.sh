#!/bin/sh
# 第五批：**把「忍」从阈值开关换成真算一次概率**〔2026-10-23〕
#
# 用户给的场景和指令（原话）：
#
#   「堆上就一张 2，而你手牌有 2，轮到你出牌
#     1、如果已收卡牌有 2 张 2，那忍 1 手大概率是赚的，极力推荐
#     2、如果已收卡牌有 1 张 2，那就要考虑牌组厚度，计算概率是否要忍 1 手
#     3、如果已收卡牌没有 2，那就要考虑牌组厚度，计算概率是否要忍 1 手」
#   「现在要做的就是考虑牌组厚度计算概率和收益，
#     提高 4/5 档的积分让计算偏向忍 1 手」
#
# ---- 这一批跟前四批的根本差别 ----
#
# 前四批的「忍」是个**阈值开关**：判据 `later·p > now·100` 里一个局面变量
# 都没有，所以 c ≤ 16 永不忍、c ≥ 17 永远忍，中间没有「有时候」。
# 那样的 AI 结构上不可能「开始考虑」—— 而那是用户的验收线。
#
# `HOLD_EV=1` 之后判据里有三个逐手都不同的量：
# **牌库厚度、对手手牌张数、这个点数外面还剩几张**。
#
# ⚠ 所以**前四批的「窗口只有一个整数宽」那个结论不适用于这一批** ——
#   那是阈值打法的性质，不是游戏的性质。两批的数不能相减。
#
# ---- 作废公告：**前四批所有 `HOLD_ONCE` 的数全废**〔2026-10-23〕 ----
#
# 查出来的 bug：`ai.js` 挑饵那段的分层开关原来是 `const HOLD_PEN = hmin > 0`，
# 只认 `HOLD_MIN`。而 `HOLD_ONCE` 不设 `HOLD_MIN` → `hmin = 0` → 分层没开 →
# 挑饵只按 `baitRisk` 排，**它不看这张饵自己会不会钓到**。
#
# 于是判了「忍」之后扔出去的饵匹配上堆顶，当场收 2 张 —— **根本没忍成**。
# 这个病 2026-10-22 在 `HOLD_MIN` 上抓过一次（实测 46% 的「忍」照样收了牌，
# 墓碑在 ai.js:952），补的时候 `HOLD_ONCE` 还不存在，所以没被带上。
#
# 跟着废的（都带着这个 bug 跑的）：
#   · 1,4,17 那一组：忍 0.96 手/局、升档 15.2%、没升 76.5%、分差 +0.19
#   · 「c ≤ 16 一次不忍 / c ≥ 17 全忍」那条窗口结论
#   · 第三批 C 段整张表（1,4,12 / 20 / 40 / 100 / 400）
#   · 第四批甲乙丙三段
# 「忍了 N 手」这个数本身是**虚高**的 —— 里头混着没忍成的。
#
# ⚠ **不受影响**：`base`（根本没开 HOLD_ONCE）、全技能表、所有 X / D。
#   这个 bug 只在 `HOLD_ONCE=1` 那条路上。
set -e
# ⚠ **这一行 2026-10-23 晚些补的，别删。** 当天 `HOLD_ONCE` / `HOLD_EV` /
#   `HOLD_BOTH` 三个旋钮的默认值全翻成了「开」，而这个脚本是按**翻之前的默认**写的。
#   这儿有两处会同时塌掉：丙段（`HOLD_P` 对照组）—— `HOLD_EV` 默认开之后
#   `HOLD_P` 那条 `else if` 到不了，于是「对照组该是开关式的」这个判据
#   会变成跟乙段逐字相同；丁段（`HOLD_BOTH=1`）会跟甲段逐字相同。
#   下面每一行的 `env X=1` 仍然覆盖这三个，所以本脚本的语义一个字没变。
#   〔2026-10-23 同日再补 `JACK_HOLD=0`：那个旋钮当天也从 0 翻成了 3
#     （用户拍板，见 ai.js 那一行）。**同一个坑的第二次** —— 不钉的话
#     本脚本每一段都变成「守 3 张闸的 AI」跑的，而它写的是「不守」〕
export HOLD_ONCE=0 HOLD_EV=0 HOLD_BOTH=0 JACK_HOLD=0
cd "$(dirname "$0")/../.."
N=${1:-20000}
S=tools/md-sim/sim.js

pick() {
  awk '
    /后手分差/ { print "      " $0; next }
    /忍了|算了|外面还剩|档起|情况 3|它信的|其中|⚠/ { print }
  '
}

echo "######## 甲 主轴：固定 2/3 档 = 1，把 4/5 档的 b 往上推 ########"
echo "〔c 固定 20。要看四件事（第四条是用户 2026-10-23 加的，也是最硬的一条）："
echo "   一、判忍率**不能是 0% 或 100%** —— 那还是阈值开关；"
echo "   二、「外面还剩」三个桶的判忍率要**拉得开**（剩 0 张那桶该几乎全忍）；"
echo "   三、后手分差 |·| < 2×se，而且忍了 > 0；"
echo "   四、**「情况 3 · 牌组厚」那一格的判忍率不能贴着 0%** ——"
echo "       用户：「我希望在情况 3（已收卡牌没有 2）且牌组还很厚的条件下，"
echo "       忍 1 手还是有价值的，4/5 档的积分要有这样的价值」。"
echo "       贴着 0% = b 还没给够，往上推；而「牌组薄」那一格该明显更低。"
echo "   另看：「4/5 档起」的判忍率该远低于「2/3 档起」（用户预判 4→6 不该忍）。〕"
for b in 2 3 4 5 6 8 10; do
  echo ""
  echo "==== 1,$b,20 ===="
  env SCORE_BANDS=1,$b,20 HOLD_ONCE=1 HOLD_EV=1 node $S base -n "$N" 2>&1 | pick
done

echo ""
echo ""
echo "######## 戊 同一条 b，但 c 跟着抬（保住 6/7 档的「画饼」身份）########"
echo "〔甲把 c 钉在 20，b 推到 8/10 时 c 已经不够远了 —— 那时 4→6 会开始划算，"
echo "  而用户预判「4 升 6 一定不推荐忍」。这一段令 c = 3b，比值不变，"
echo "  用来分清「情况 3 判忍率上去了」是 b 的功劳还是 b/c 变近的副作用。〕"
for b in 4 6 8 10; do
  echo ""
  echo "==== 1,$b,$((b * 3)) ===="
  env SCORE_BANDS=1,$b,$((b * 3)) HOLD_ONCE=1 HOLD_EV=1 node $S base -n "$N" 2>&1 | pick
done

echo ""
echo ""
echo "######## 乙 对照：同样的档值，换回阈值开关 HOLD_P=25 ########"
echo "〔这一段证明「graded 还是开关」是 HOLD_EV 带来的，不是档值带来的。"
echo "  对照组该呈现：判忍率贴着 0% 或 100%，三个桶分不开〕"
for b in 4 6; do
  echo ""
  echo "==== 1,$b,20 · HOLD_P=25（旧打法） ===="
  env SCORE_BANDS=1,$b,20 HOLD_ONCE=1 HOLD_P=25 node $S base -n "$N" 2>&1 | pick
done

echo ""
echo ""
echo "######## 丙 对称自检：双方都用 EV，分差该 ≈ 0 ########"
echo "〔两侧同打法，分差显著不为 0 = 实现有问题，甲的结论先别信〕"
for b in 4 6; do
  echo ""
  echo "==== 1,$b,20 · HOLD_BOTH=1 ===="
  env SCORE_BANDS=1,$b,20 HOLD_ONCE=1 HOLD_EV=1 HOLD_BOTH=1 node $S base -n "$N" 2>&1 | pick
done

echo ""
echo ""
echo "######## 丁 失手那一支算不算「对手收走多少」########"
echo "〔HOLD_EV_FOE=0 把它关掉。关掉 = 只算自己的得失，忍会变激进。"
echo "  两档的差就是「把它当成一场赌」这个建模选择值多少〕"
for f in 1 0; do
  echo ""
  echo "==== 1,4,20 · HOLD_EV_FOE=$f ===="
  env SCORE_BANDS=1,4,20 HOLD_ONCE=1 HOLD_EV=1 HOLD_EV_FOE=$f node $S base -n "$N" 2>&1 | pick
done

echo ""
echo "#### 怎么判："
echo "####   甲 找同时满足这四条的那个 b："
echo "####      判忍率在 0%/100% 之间、三桶拉得开、分差 |·| < 2se、"
echo "####      **「情况 3 · 牌组厚」判忍率明显 > 0 且明显高于「牌组薄」**。"
echo "####      四条同时成立才算「AI 开始考虑」。"
echo "####   乙 对照组该是开关式的。要是它也 graded，那 HOLD_EV 就没立功。"
echo "####   丙 两格都该 ≈ 0。不为 0 先查实现。"
echo "####   丁 差多少记进台账，别当成噪声。"
