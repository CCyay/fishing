#!/bin/sh
# **把「平」拆成两支**：`HOLD_EV_SPLIT` 的 A/B〔2026-10-23 第八跑〕
#
# 用户原话：「对手手里既没有 2、也没有 J 是对的，**也配不上我那张饵**
#            要拎出来单独算」。
#
# ---- 拆的是赔付，不是概率 ----
#
# 原来一支「平」赔付一律记 `now`。而两件事的赔付**不一样**：
#   · **饵被吃**  ：他收走「饵 + 他那张」，堆退回 L 张 → 我照收 `bestCaught`。**精确**
#   · **浅层被吃**：他从 `shalMin` 切到堆顶，**把我目标上面的牌一起端走**
#                   → 我只收 `shalMin − at + 1` 张。**原来记成 now，高估**
#
# 概率那头只多了一次 `missP(D+S)`，夹在原有的 `missP(D)` 和 `missP(D+S+B)` 之间；
# 三个出口集互不重叠，所以**拆完两支相加 == 原来那一支**。
# ⚠ **不能写成乘积** `missP(D)×missP(S)` —— 超几何不放回，乘积高估。
#
# ---- 这一跑要回答三件事 ----
#   一、**退化自检**：旋钮关着时逐字同行为（甲段 + 乙段对上第七跑的数）
#   二、**高估了多少**：诊断行「没拆时每次高估 N 分」——
#       那一截 ≈0 的话这个旋钮白加，要如实报
#   三、**拆完打法变了多少**：判忍率、分差、按档汇总
set -e
# ⚠ **这一行 2026-10-23 晚些补的，别删。** 当天 `HOLD_ONCE` / `HOLD_EV` /
#   `HOLD_BOTH` 三个旋钮的默认值全翻成了「开」，而这个脚本是按**翻之前的默认**写的。
#   不钉住的话前四段全变成对称（分差恒≈0），而第五段（`HOLD_BOTH=1`
#   那个对称自检）会跟第四段逐字相同 —— `HOLD_EV_SPLIT` 的 A/B 整个读不出来。
#   下面每一行的 `env X=1` 仍然覆盖这三个，所以本脚本的语义一个字没变。
#   〔2026-10-23 同日再补 `JACK_HOLD=0`：那个旋钮当天也从 0 翻成了 3
#     （用户拍板，见 ai.js 那一行）。**同一个坑的第二次**，坏的是甲乙丙己四段
#     （它们不写 JACK_HOLD）—— 甲段那条「逐位复现 R3」会失败，
#     而丙段会跟丁戊两段的「J 守 3 张闸」撞成同一个条件，A/B 整个塌掉。
#     丁、戊的 `JACK_HOLD=3` 照旧覆盖，语义不变〕
export HOLD_ONCE=0 HOLD_EV=0 HOLD_BOTH=0 JACK_HOLD=0
cd "$(dirname "$0")/../.."
N=${1:-20000}
S=tools/md-sim/sim.js
B=1,4,12

pick() {
  awk '
    /按档汇总/ { c = 1 }
    c == 1 { print; if (/6\+ 档/) c = 0; next }
    /后手分差|后手胜率/ { print "    " $0; next }
    /忍了|算了|其中「平」|外面还剩|档起|情况 3/ { print }
  '
}

echo "######## 甲 退化自检：旋钮全关，必须逐位复现 R3 ########"
echo "〔要的八个数：后手分差 −0.07(se 0.08)、每人每局 21.8 分、"
echo "  每次平均收 2.85、钓到 7.7 次、出牌 23.0。对不上就先别往下读〕"
node $S base -n "$N" 2>&1 | grep -E "后手分差|每人每局|平均收|每次收|出牌|钓到"

# ⚠ **2026-10-23 用户定：`HOLD_EV_SPLIT` 默认翻成「开」。**
#   所以「没拆」那两段现在要**显式写 `=0`**，不能靠不写。
#   〔头一跑时是反过来的：默认关、拆的那两段写 `=1`。数一样，口径一样〕
echo ""
echo "######## 乙 没拆（= 第七跑那一格，复现 + 新诊断行） ########"
echo "〔后手分差该是 +0.86(se 0.08)、判忍 26.9%。对不上说明我动到了别处〕"
env SCORE_BANDS=$B HOLD_ONCE=1 HOLD_EV=1 HOLD_EV_SPLIT=0 node $S base -n "$N" 2>&1 | pick

echo ""
echo "######## 丙 拆了（**现行默认**） ########"
echo "〔该是 +0.90(se 0.08)、判忍 26.1%、4/5 档起判忍 12.0%〕"
env SCORE_BANDS=$B HOLD_ONCE=1 HOLD_EV=1 node $S base -n "$N" 2>&1 | pick

echo ""
echo "######## 丁 候选 AI（J 守 3 张闸）· 没拆 ########"
env SCORE_BANDS=$B JACK_HOLD=3 HOLD_ONCE=1 HOLD_EV=1 HOLD_EV_SPLIT=0 node $S base -n "$N" 2>&1 | pick

echo ""
echo "######## 戊 候选 AI（J 守 3 张闸）· 拆了（**现行默认**） ########"
env SCORE_BANDS=$B JACK_HOLD=3 HOLD_ONCE=1 HOLD_EV=1 node $S base -n "$N" 2>&1 | pick

echo ""
echo "######## 己 对称自检：戊段两侧都开 ########"
echo "〔分差该回到 −0.07 量级，两侧计数该逐位齐。不齐则戊段先别信〕"
env SCORE_BANDS=$B JACK_HOLD=3 HOLD_ONCE=1 HOLD_EV=1 HOLD_BOTH=1 \
  node $S base -n "$N" 2>&1 | pick

echo ""
echo "#### 怎么判："
echo "####   一、甲段对不上 R3 → 我改坏了别处，后面全不作数。"
echo "####   二、乙段「没拆时每次高估 N 分」就是这个旋钮的全部作用面。"
echo "####      ≈0 → 拆了白拆，如实报，别为了交差说它有用。"
echo "####   三、丙 − 乙、戊 − 丁 = 拆出来值几分。两组方向该一致；"
echo "####      不一致说明它跟 JACK_HOLD 有交互，那得单独量。"
echo "####   四、拆完判忍率该**下降**（赔付被改小了，忍变得没那么划算）。"
echo "####      反而上升的话先查实现，别先讲故事。"
echo "####   五、〔2026-10-23 默认翻成「开」之后加的〕每段行尾那个"
echo "####      「（已拆）/（没拆）」要跟段名对得上：乙丁 = 没拆、丙戊己 = 已拆。"
echo "####      对不上说明 sim.js 那个标记又写了一份自己的 env 判断。"
