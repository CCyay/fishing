#!/bin/sh
# 【死水】四格矩阵 —— 挑几张（DEAD_N）× J 能不能挑（DEAD_JACK）〔2026-10-26〕
#
# 起因是用户那一句：「死水 看着调整 挑多张或J也能挑」。
# 两条轴各两档 = 四格，**一次量全，不边推边量**（CLAUDE.md 那条：
# 顺子族那一轮五层推算层层错，而文档早写明设计空间有几格）。
#
# 现行档 = `DEAD_N=2` / `DEAD_JACK` 关，也就是**第一格就是现行行为** ——
# 所以第一格该复现台账里死水那一行（R4、A 槽）。复现不了就先查代码，
# 别急着解释新档（「数据反常先查代码」）。
#
# ---- 读哪几个数，以及一个必须避开的读法 ----
#
#   甲 X —— 合格区间 +1.0 ~ +5.5（用户 2026-10-26 定）。
#   乙 D —— 超 3.03 的话后手买了会亏。
#   丙 诊断口（`proto-diag.js` 自己会把 `dead` 那一段打出来）：
#        `fires` 是分母，**先看它**；`killed/(fires×N)` 是兑现率；
#        `short*` 是「池子不够 N 张」的累计缺口 —— N 往上调迟早撞到它。
#
# ⚠ **J 那一档的增量不能从 X 的差里读。** `DEAD_JACK=1` 一开，
#   X 的差里混着两样东西：真多废掉的那些 J（看 `jackMine/Foe`），
#   以及**「J 不再通吃 → 局面变长」那条副作用**（死水是改写牌
#   `card.rank = ZERO_RANK`，于是被置 0 的 J 自动失去通吃）。
#   所以 J 的净贡献读 `jackMine/Foe`，X 只用来判合格区间。
#
# ⚠ `DEAD_JACK=0` 时 `jackMine/Foe` 必须是 **0**。不是 0 就是旋钮没接上，
#   那四格的数全不能用（这正是第四节那条「X 之外必须有计数」的用处）。
#
# ---- ⚠⚠ `DEAD_N=3` 那两格**不管量出多少都不能上架**（判据挡着，不是数） ----
#
# `DEAD_COUNT` **不是死水自己的参数，是全表「动对手手牌」类的通用标尺**
#（`draw-skills.uts:354-359` 写着「拿手牌数的一半」），而它自己那段注释
# 就把 3 判死了：「废 3 张等于他两个回合只能垫牌 —— 那不是压制是处刑」。
#
# 更要紧的是**别的三件正靠这把尺子定上限**，改它会连带挖空它们的立论：
#   `:330`      某件盲选件 N=2 量出 +4.73、`DEAD_COUNT` 把上限压到 2；
#   `:423/440`  【冻结】那个 3 张（「3 张留一张能打，照 DEAD_COUNT 那条尺子」）；
#   `:528-530`  【退潮】N=3 可以、N=4 越线（「贴 3 张之后他手里还剩 1 张干净的」
#               —— ⚠ 它能到 3 是因为**贴标签 ≠ 废掉**，贴过的牌照样打得出去，
#               所以那一条**不能反过来给死水当先例**）。
#
# 那两格照旧跑，理由有两条：①「一次把矩阵量全，不边推边量」；
# ② 它顺带给那把尺子配一个实测值 —— 这把尺子从来只有判据没有数。
# **但读数时 N=3 是「这把尺子值多少」的旁证，不是死水的候选档。**
#
# 于是真正的候选只剩 `DEAD_JACK` 那条轴 —— 而它**完全不碰那把尺子**
#（张数不变，变的是「哪些牌进得了池子」）。
#
# ---- 真要上架 `DEAD_JACK` 的话，源码侧有**四处**要一起改 ----
#
# 查过了（`ap-fishing.uvue`）。**四处必须一起改，漏一处是静默的** ——
# `rules.js:4307-4309` 那段注释写的正是这个形状：「只改一处的话 AI 挑了 J
# 而结算 return，于是『挑了 N 张』变成『挑了 N−1 张』，而 X 照旧有数」。
#
#   `:9820 deadPool`    挑选池的 J 过滤（玩家和庄家共用这一个池）
#   `:9841 doDead`      结算守卫（`card.rank == JACK` 那道闸）
#   `:8185 canPickFoe`  界面闸（不改的话那张 J 没有 card-pickable，点不动）
#   `:9856 foeDeadPick` 庄家的尺子 —— ⚠ **必须照模拟器给 J 钉 100**
#                       （`ai.js:1729-1734`）。只放开池子的话 `card.value`
#                       对 J 不是 100 那一档，庄家几乎永远挑别的牌 →
#                       `jackFoe` 贴着 0，**而 X 照旧有数**，那一档静默空转
#
# 另外两处文案：`draw-skills.uts:2127` 的 `desc` 去掉「；J 不能挑」，
# 而 `:2042` 往下那段「为什么排掉 J」的理由要**搬成墓碑**、不要留在原地
#（留在原地的注释是现在时写的，读起来像那条闸还在）。
# `draw-terms.uts` 不用动 —— 查过，它只写置 0 的优先链，没写死水的 J 规则。
set -e
OUT=tools/md-sim
N=20000
DIAG=6000

cell() {
  n=$1; jack=$2
  echo "############ DEAD_N=$n  DEAD_JACK=$jack ############"
  DEAD_N=$n DEAD_JACK=$jack \
    node $OUT/sim.js one dead -n $N > $OUT/out-dead-$n-$jack.txt 2>&1
  grep -E 'X|D|标准误|口径' $OUT/out-dead-$n-$jack.txt | head -12
  echo "---- 诊断口（$DIAG 局）----"
  DEAD_N=$n DEAD_JACK=$jack \
    node $OUT/proto-diag.js dead $DIAG > $OUT/out-dead-diag-$n-$jack.txt 2>&1
  grep -E '分差|dead:' $OUT/out-dead-diag-$n-$jack.txt
  echo ""
}

# 第一格 = 现行档，拿它当回归基准
cell 2 0
cell 2 1
cell 3 0
cell 3 1
