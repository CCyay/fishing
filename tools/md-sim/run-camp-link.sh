#!/usr/bin/env bash
# 2026-10-20 ·【点数互通】的最后一格：**campaign 口径**（庄家也强的那一档）。
#
# 前面三个口径（role 满配 / duel 无天花板 / proto-link 扫描）全是
# **1v1 单局**，而这件技能的定档疑点正是「它会不会在庄家也强的时候爆掉」——
# 那只有闯关答得了。
#
# ---- 先读这几条，不然数会读错 ----
#
# **一、默认档一个字节都没动。** `campaign.js` 2026-10-20 加了两个环境开关
#（`PLAYER_ROLE` / `PLAYER_SP`），两个都默认关着。§0 跑的就是默认档，
# 它必须跟台账里 10-19 那三档通关率逐位相同 —— 不同就是我改坏了，**先停**。
#
# **二、`PLAYER_SP=1` 不是「加了互通」，是「常驻技从无到有」。**
# 之前 `playGame` 根本没传 `myRole`，于是 campaign 里**一件常驻技都没模**，
# 连玩家自己那张江口闸官的【窄口】都没有。所以 §1 是必须的对照 ——
# 跳过它的话，§2 的涨幅里混着「窄口第一次生效」那一份。
#
# **三、要对的是 §2 和 §3，不是 §2 和 §0。**
# 【通号人】3 槽、【夜钓客】3 槽且槽标签一模一样（A/5/9）——
# 于是两档的配装件数、覆盖面、rng 消耗全相同，只差常驻技那一件。
# 而拿 §2 去减 §1（lock，4 槽）的话，差里混着**少插一件**那一份。
#
# **四、看诊断行的实际倍率。** ×1.00 = 一次都没发动，那一档的数作废。
# 理论值：通号人 ×3、通号人·双槽 ×2。
set -u
N=${N:-2000}
cd "$(dirname "$0")/../.."

echo "################ 0. 默认档（两个开关都关）—— 必须跟 10-19 逐位相同 ################"
node tools/md-sim/campaign.js -n "$N"

echo
echo "################ 1. 对照：常驻技从无到有（还是江口闸官，4 槽 / 16 张）################"
# 这一档开的是【窄口】（lock 的常驻技）。它跟互通无关，纯粹是
# 「campaign 第一次模常驻技」的基线。§0 → §1 的差 = 窄口 + 这一类从 0 到 1
PLAYER_SP=1 node tools/md-sim/campaign.js -n "$N"

echo
echo "################ 2. 【通号人】（3 槽 A/5/9，12 张，常驻 = 点数互通）################"
PLAYER_ROLE=linkman PLAYER_SP=1 node tools/md-sim/campaign.js -n "$N"

echo
echo "################ 3. 对照：【夜钓客】（**同槽同覆盖**，常驻 = 两色）################"
# 这才是 §2 的正确对照。1v1 那边两张卡的差实测 +6.15（duel，无天花板），
# 而夜钓客的【两色】在那套满配下恰好值 0（查 sameSuit 的五处调用查出来的）——
# 闯关这边配装是**随机抽**的，两色会不会被激活是另一回事，所以这个差
# **不保证**还是互通的净值。看倍率行判断
PLAYER_ROLE=night PLAYER_SP=1 node tools/md-sim/campaign.js -n "$N"

echo
echo "################ 4. 【通号人·双槽】（2 槽 A/5，8 张）—— 覆盖面那条线 ################"
# ⚠ 2 槽 → 配装封顶 2 件，比上面三档少插 1~2 件。
# 它不跟 §2 构成控变量，只回答「这个形状在闯关里撑不撑得住」
PLAYER_ROLE=linktwo PLAYER_SP=1 node tools/md-sim/campaign.js -n "$N"

echo
echo "################ 5. 源码有没有漂（只动了模拟器，该全绿）################"
node tools/md-sim/fingerprint.js

echo
echo "################ 跑完 ################"
