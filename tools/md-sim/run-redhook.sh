#!/usr/bin/env bash
# 2026-10-20 ·【红钩】/【桃汛客】上架之后，补量**上架那张卡的形状**。
#
# ---- 为什么需要这一份（run-heart.sh 不够）----
#
# run-heart.sh 量的是两张**载体卡**：
#   heartman  2/7/Q（跟串钩手同形，为的是两件常驻技能直接相减）
#   heartslot 2/7/♥（用户原案，21 张）
# 而上架的【桃汛客】是 **♥/5/10** —— **跟两者都不一样，没有单独量过**。
#
# 跟 heartslot 的关系是「同形不同号」：
#   覆盖面一样（13 + 4 + 4 = 21 张）、花色槽都是 ♥、都是「♥槽 + 两个点数槽」。
#  〔花色槽按 13 算是**模拟器**的口径；源码的 slotCover 按 12 算（J 不触发），
#   那边两张都是 20。这是一处已知的、还没定的不一致 —— 见设计文档『角色与槽』。
#   两张卡在**同一侧**算出来相等，所以这里的横比不受它影响〕
#   差的只有那两个点数的**标签**（2/7 → 5/10），而我当时预期标签不中性：
#     · 【囤饵】的 baitRankOf 取**第一个数字槽** → heartslot 塞 2、桃汛客塞 5
#     · 点数本身进「吃水」那笔账（5/10 是两端，2/7 偏低）
#   所以 heartslot 的数是**邻格**，不是这一格。本脚本就是补这一格。
#
#  〔✅ 补完了：**标签是中性的**（§5b，+7.69 vs +7.66，0.15σ）。
#    上面两条理由都没在分上体现出来。两张卡那 4.4 分的差全在
#    「♥ 槽排第几」上 —— 见 §5b〕
#
# ---- 零点 ----
#
# 【红钩】上架后对带它的角色**无条件生效**（跟 linkOn 一样），
# 但 `HEART_OFF=1` 这个旋钮**专门留着** —— 就为了保住
#「同一张卡、同槽、同插件、同种子，只差这一件常驻技」这个干净零点。
# 删掉它的话这一格就再也量不出来了。
#
# ⚠ `role` 口径的对手**不带角色**，满配胜率 95~98% ——
#   **胜率一过 95%，增量就不能当强度读**。所以 §4 不是可选项。
set -u
N=${N:-6000}
cd "$(dirname "$0")/../.."

echo "################ 0. 结构 ################"
node tools/md-sim/refs.js 2>&1 | tail -12
echo
node tools/md-sim/check.js 2>&1 | tail -4

echo
echo "################ 1. 三道闸：手算得出来的用例 ################"
# 桃汛客 ♥/5/10，三个槽插满 0/1/2（0=♥槽、1=5槽、2=10槽）：
#   ♥7   → [0,1,2]  7 不在任何点数槽上，靠「它是 ♥」把三件全点着
#   ♥5   → [0,1,2]  本来就命中 ♥槽 + 5槽，再补上第三件
#   ♠5   → [1]      **闸**：不是 ♥，只有 5 槽那一件
#   ♠10  → [2]      同上
#   ♥J   → []       **闸**：J 只有通吃 —— 连 ♥ 槽本身都不响
#                   （漏了它覆盖面就从「13 张里能用 12 张」变成 13 张）
#   ♦3   → []       两道都不沾
node -e '
const R = require("./tools/md-sim/rules.js")
const ri = R.roleIndexOf("peachtide")
if (ri < 0) { console.error("✗ 查不到角色 peachtide"); process.exit(1) }
const lo = R.kitFromRole(ri, [0, 1, 2])
const G = { loadouts: [lo, lo], roles: [] }
G.roles[R.ME] = ri
G.roles[R.FOE] = -1
console.log("  【" + R.DRAW_ROLES[ri].name + "】槽 "
  + R.DRAW_ROLES[ri].slots.join(" / ") + "（" + R.roleCover(ri) + " 张）")
for (const t of [["♥","7"],["♥","5"],["♠","5"],["♠","10"],["♥","J"],["♦","3"]]) {
  const mk = () => ({ rank: t[1], suit: t[0], value: 1, extra: [] })
  console.log("    " + t[0] + t[1] + "\t我方 [" + R.skillsOf(G, R.ME, mk())
    + "]\t对手 [" + R.skillsOf(G, R.FOE, mk()) + "]")
}
console.log("    ↑ ♥7/♥5 该是三件；♠5 → [1]、♠10 → [2]；♥J 和 ♦3 该是空的")
console.log("    ↑ 对手那一列该全是**普通触发**（他不带这件常驻技）")
console.log("")
console.log("  ---- 覆盖面对照（同形不同号）----")
for (const k of ["peachtide", "heartslot", "heartman", "rigger"]) {
  const i = R.roleIndexOf(k)
  console.log("    " + R.DRAW_ROLES[i].name + "\t"
    + R.DRAW_ROLES[i].slots.join(" / ") + "\t" + R.roleCover(i) + " 张")
}
console.log("    ↑ 桃汛客和红心人·花色槽该是**同一个张数**（21）——")
console.log("      不一样的话下面那个「邻格」的说法当场不成立")
'

echo
echo "################ 2. 零点：裸的 ♥/5/10（HEART_OFF=1）################"
# 这一行是净值减法的零点。它跟上架的【桃汛客】只差一件常驻技。
# ⚠ 顺带也是「♥ 槽本身值多少」那笔账的一头 ——
#   跟 run-heart.sh §2（裸的 2/7/Q）相减就是**多一个 ♥ 槽**值多少
HEART_OFF=1 node tools/md-sim/sim.js role peachtide -n "$N"

echo
echo "################ 3. 上架档：【桃汛客】带【红钩】################"
# 净值 = 本节 − 第 2 节。
#
# ⚠ 预期它**比 heartman（2/7/Q）那一格低得多**，而那不是 bug ——
#   自带 ♥ 槽是个**内部刹车**：♥ 牌本来就点着 ♥ 槽那一件，
#   【红钩】只能补上剩下两件，而「同一手的第 2、3 件」几乎不值钱
#  （实测 新增第一件 1.86 分/件 vs 再叠一件 0.12 分/件，差 15 倍）。
#   这一节要验的就是这条判据在 5/10 这对点数上照样成立。
node tools/md-sim/sim.js role peachtide -n "$N"

echo
echo "################ 4. 无天花板复核（这一节才是定档用的数）################"
# 双方同卡、同插件，**只有我方带这件常驻技** → 胜率贴着 50%，
# 读出来的差才是它真正值多少
HEART_SIDE=me node tools/md-sim/proto-link.js "$N" --duel peachtide peachtide

echo
echo "################ 5. 邻格对照：用户原案 2/7/♥（同形不同号）################"
echo "---- 零点 ----"
HEART_OFF=1 node tools/md-sim/sim.js role heartslot -n "$N"
echo
echo "---- 开 ----"
node tools/md-sim/sim.js role heartslot -n "$N"
echo
echo "---- 邻格的无天花板那一格（**跟 §4 比，别跟上面两行比**）----"
# 加这一节是因为 2026-10-20 第一次跑完发现**两个口径不吻合了**：
# 桃汛客 role 净值 +2.05，而 duel +3.25 —— 差 1.20（约 4σ）。
# 以前这一族两个口径一直吻合（串钩 6.52/6.68、红心人 12.92/13.54、
# 归方 1.09/1.02），而那几格的**零点**胜率都低得多。
# 这两张卡的零点已经 97.1% / 96.7%，所以 role 口径那个差
# **可能有一部分是天花板压出来的，不是点数标签造成的**。
# 不补这一行的话「点数标签不中性」就只是个猜测
HEART_SIDE=me node tools/md-sim/proto-link.js "$N" --duel heartslot heartslot
echo
echo "⚠ §2/§3 和上面两行是 role 口径，**而它们的零点都已经过 95%** ——"
echo "  所以横比要用 §4 减这一行，不是用两个 role 净值相减。"
echo "  ⚠ 但 §4 跟这一行差的**不止点数标签**（还差「♥ 槽排第几」）——"
echo "  别把这个差读成标签的值。拆它的是 §5b。"

echo
echo "################ 5b. 拆混淆：♥ 槽排第几 vs 点数标签 ################"
# ⚠ §4 和 §5 那两张卡差的**不止点数标签**。`kitFor` 按槽下标填
# KIT_ORDER（传火 / 引火 / 对换），所以：
#   桃汛客   ♥/5/10 → ♥ 槽里是**传火**（最强）→ 打 ♥ 时红钩只能补两件弱的
#   heartslot 2/7/♥ → ♥ 槽里是**对换**（最弱）→ 红钩补的是传火 + 引火
