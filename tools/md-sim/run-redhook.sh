# ✅ 2026-10-20 跑过了：**+7.69 ±.14** —— 是第一种。
#    点数标签 5/10 vs 2/7 差 **0.03 = 0.15σ（中性）**；
#    ♥ 槽排第几 差 **4.44（约 22σ）**。这一行要是哪天不再 ≈7.7 就是 rules.js 动了。
HEART_SIDE=me node tools/md-sim/proto-link.js "$N" --duel peachlast peachlast
echo
echo "⚠ 结论（已坐实）：KIT_ORDER 那个填法**不是中性的测量约定，是强变量**。"
echo "  游戏里槽放什么是玩家自己选的 —— 所以【桃汛客】真实强度是"
echo "  **+3.25 ~ +7.7 的区间**，♥ 槽插最强的那件 = 自己把常驻技关掉一半。"
echo "  上沿超出常驻技档位（+3~5.5），而玩家看不见这条。"
echo "  🔴 §5c 是对它的处理（2026-10-28 用户定稿）。"
echo "  ⚠ 而 §4 / §5 / §5b 那三个数 2026-10-27 **全废了** ——"
echo "    对换删了（§5b 注释里那个「♥ 槽坐对换」的前提不存在了），"
echo "    而且 KIT_ORDER 同日换了两次。所以这三行现在是**重跑取数**，"
echo "    不是「对一下还是不是 3.25 / 7.66 / 7.69」。"

echo
echo "################ 5c. 🔴 定稿：撤掉 ♥ 槽（2026-10-28）################"
# 用户在四条路里定了这一条：**`slots: ['5','10']`，红钩留着**。
# 代号卡 `peachnoheart`，源码侧还没落地（照「原型放模拟器、先量再落地」）。
#
# 它成立靠一条查实现查出来的事：**【红钩】不需要 ♥ 槽** ——
# `addHeartWild` 只看 `card.suit`，`suitOwner['♥']` 空着也照样把
# 所有被占的槽追加进去。于是打任意 ♥ 仍让两个点数槽全响，
# 而**♥ 上不坐技能** ⇒ §5b 那个「♥ 槽排第几」的暗旋钮**从根上消失**。
#
# ⚠ 净向**推不出来**：松掉 ♥ 那个刹车（升）对少一个槽少一件技能（降）。
# ⚠ 别拿「没 ♥ 槽的 2/7/Q 版 13.54」去推它 —— 那张是 3 槽 3 件技能。
echo "---- 形状硬计数（不跑对局，只取决于 skillsOf）----"
node tools/md-sim/fires.js peachtide
node tools/md-sim/fires.js peachnoheart
echo
echo "---- 这一刀砍了多少：卡对卡，无天花板 ----"
# 两张卡都带红钩，所以这一格读的是**形状差**，不是常驻技差。
# ⚠ 槽数不同（3 vs 2），所以它**不能**当「某一件技能值多少」读 ——
#   能读的就是「新形状比现行弱多少」，而那正是这一轮要的那个数
node tools/md-sim/proto-link.js "$N" --duel peachnoheart peachtide
echo
echo "---- 红钩在新形状上还值多少（定档看这个，档位 +3~5.5）----"
HEART_SIDE=me node tools/md-sim/proto-link.js "$N" --duel peachnoheart peachnoheart

echo
echo "################ 5d. 🔴 第二刀：红桃只「选 1 件」发动（2026-10-28 定稿）################"
# 用户原话：**「红桃牌能够选择1个技能发动」**。它对应**现成旋钮**
# `HEART_PICK=one`（rules.js:4647）—— **零改码**。
#
# ⚠ 一处标明的假设：按的是「**追加** 1 件」，不是「总共只响 1 件」。
#   `addHeartWild` 往 `out`（已含槽命中）里 push，「追加」是它本来的语义；
#   按「总共 1 件」读会让**打 ♥5 比打 ♠5 还少响**。另一种读法要改 1 行。
#
# 形状（从实现推得死）：**覆盖面 18 不变、件次 30 → 20** ——
#   `4694` 那道 `out.indexOf(o) < 0` 去重闸在 `one` 的 return **之前**，
#   所以 ♥5 跳过已在 out 里的 5 槽件、push 10 槽件 ⇒ **♥5 照旧响 2 件**。
#   ⇒ 这一刀拉的是**件次**那一轴（0.12 分/件次），不是覆盖面（1.86）。
#
# ✅ 2026-10-28 跑了满配：**+13.30 / 81.0%**（n=6000、SE 0.27）——
#    对照同卡 `all` 档 22.49/96.5% ⇒ 掉 9.19，而真降幅更大（那一格被天花板压扁）。
#    🔴 **胜率 81% ⇒ 这一族第一个能直读的满配数。**
#    诊断口核实了手算：件次 2.73 → 6.73 = **×2.46**，静态比 **20/8 = 2.50**。
#    ⚠ 别拿 §3/§5 那个 ×2.10 当验收线 —— 那是 peachtide（3 槽/18 张）的数，跨卡比。
echo "---- 形状硬计数（秒出，先跑这条：对不上，下面的分值都不能要）----"
HEART_PICK=one node tools/md-sim/fires.js peachnoheart
echo
echo "---- 满配（✅ 已跑：+13.30 / 81.0%）----"
HEART_PICK=one HEART_SIDE=me node tools/md-sim/sim.js role peachnoheart -n "$N"
echo
echo "---- 🔴 定档那一格（无天花板）—— ✅ 已跑：+6.67 ±0.19 ----"
# ⚠ 13.30 是**满配**（含两件插槽技能），**不是红钩这一件的净值** —— 两个口径不能相减
#
# 🔴 档位那条线这一轮查实过，**它换过三代**（技能与关卡设计.md:2265、2336）：
#    R1 +3~5 → R3 +2.7~4.5 → R4「还没定」→ **R6 `+0.6 ~ +5.5`，每跑现算**
#   （上限 5.5 是用户定的常数，下限是胜率线 =（平局%/2）÷ 斜率）。
