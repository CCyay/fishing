echo "  🔴 原先这儿印的「三个条件」里**有两个作废了**（2026-10-28）："
echo "     ✗ 满配 ~13.17~23.37~ → 实况 **10.17~27.32**（§6 自己重跑出来的）"
echo "     ✗ 「跟【串钩】分得开」 → **串钩要撤掉**，这条判据没有对象了"
