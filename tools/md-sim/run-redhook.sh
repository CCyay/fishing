echo "  而 KIT_ORDER 是 X 降序、5 槽坐**洪水** ⇒ 固定策略挑的恰好是强的那件。"
echo "  定档用区间哪一头**要用户定**：先例【凝水】记下限 vs【清水】换 AI_SEEN 口径。"

echo
echo "################ 6. 它在全表里站哪儿 ################"
# 🔴 **~~现行角色满配区间 13.17~23.37~~ 作废了（2026-10-28 这一跑自己推翻的）。**
