#
# 读 6.67 还是 D=3.34？**读 6.67。** 实证在 run-heart.sh:117 那三对数
#（左 role 单侧净值 / 右 duel 原始差）：串钩 6.52/6.68、红心人 12.92/13.54、
# 归方 1.09/1.02 —— 三对都在 5% 内吻合 ⇒ duel 原始差 ≈ 单侧净值 ≈ X 量级。
