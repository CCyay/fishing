#!/bin/sh
# 阶梯计分 × 忍 1 手：第一批〔2026-10-22〕
#
# 用户给的五条事实：
#   1 匹配张数越多积分越多
#   2 一方占据积分优势时会换成贪心打法
#   3 对局中最多忍 1 手，忍 2 手几乎不可能
#   4 应该奖励忍 1 手的行为，这才有决策性
#   5 对局不用考虑技能 —— 技能适应规则，不是反过来
# 外加提案：轮流出牌 → 忍一手堆长 +2 → 2/3、4/5、6/7 各一档。
#
# ⚠ **这一批不能用 `fn.js` / `duel.js` 的离线重算量。**
#   那套的前提是 f 严格递增（`argmax f(N) = argmax N`，AI 选牌不变），
#   而 2/3 一档意味着 f(2)=f(3)，前提当场破。所以每一格都真跑。
#
# 读数：
#   · 「分差」是**档值**的差，不是张数的差 —— 不同 SCORE_BANDS 之间**不能相减**。
#   · 每组第二行（只有「你」忍）的分差 = **忍 1 手到底值不值**，这是事实 4 的判据。
#   · 验收看「忍 1 手诊断」那一块：hit / miss **两边都不空**才算有决策。
set -e
cd "$(dirname "$0")/../.."
N=${1:-20000}
S=tools/md-sim/sim.js

# 截取要看的三块。
# ⚠ 原先这儿用 `sed -n '/收成分布/,/^$/p'` —— **两处都是错的**：
#   表头的原文是「收 N 张的难度曲线」（`sim.js:429`），「收成分布」只在
#   `sum` 那个字段的注释里；而且 `/^$/` 会卡在标题下面那个空行上。
#   两个错叠起来的后果是**静默丢掉整张表**，不报错。
#   〔CLAUDE.md 第一节：别拿「一张表的名字」当证据 —— 这回是拿字段注释当表头〕
filter() {
  awk '
    /每人每局积分|每次平均收|后手分差|后手胜率/ { print; next }
    /忍 1 手诊断|收 N 张的难度曲线/ { on = 1 }
    /出牌时堆有多厚/ { c = 3 }
    on { print }
    /两边都不空/ { on = 0 }
    c > 0 { c--; if (c == 0) on = 0 }
  '
}

run() { # run <标题> <环境串>
  echo ""
  echo "================ $1 ================"
  echo "        [$2]"
  env $2 node $S base -n "$N" 2>&1 | filter
}

echo "#### 〇、退化自检：旋钮全关，必须逐位复现基线（后手分差 −0.07 / 每人每局 21.8）"
echo "####    check.js 的「三之二」同时验 score === taken —— 它是 scoreOf 的那个「坏得了吗」"
node tools/md-sim/check.js | tail -3
run "〇 对照（线性，现行规则）" ""

# 四组档值，每一组都有它要回答的问题 ——
#   2,3,5      近似线性的**对照组**：连这一组都有人忍，说明忍的门槛定低了
#   2,4,8      每升一档翻倍（最干净的「风险越大收获越大」）
#   1,3,8      **压低低档**：收 2/3 张只给 1 分，让「能配就配」本身变亏
#   2,6,12,24  duel.js 上一轮唯一测出**没有纯策略均衡**的那组（1/2/6/12/24）的分档版
for B in "2,3,5" "2,4,8" "1,3,8" "2,6,12,24"; do
  echo ""
  echo "########################################################"
  echo "########  SCORE_BANDS=$B  （2/3档 → 4/5档 → 6/7档 → 8+档）"
  echo "########################################################"
  run "a 双方贪心（这一档的盘子）"           "SCORE_BANDS=$B"
  run "b 只有「你」忍 1 手 ← **事实 4 的判据**" "SCORE_BANDS=$B HOLD_ONCE=1"
  run "c 双方都忍 1 手（可达性）"             "SCORE_BANDS=$B HOLD_ONCE=1 HOLD_BOTH=1"
done

echo ""
echo "#### 没跑的：事实 2（HOLD_LEAD，领先就转贪心）和事实 3 的验证（HOLD_RUN=2）。"
echo "####   两者都要先知道哪一组档值活，再挂上去 —— 现在挂等于 4 组 × 2 的空转。"
