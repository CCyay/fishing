#!/bin/sh
# 第三批：**「追 6/7 不值得」装进 AI 决策之后，6/7 档还动不动天平**〔2026-10-22〕
#
# 用户的两句话（原话）：
#   ① 「天平永远不会倒向『永远该忍』，无论 6/7 档给的多高，
#      在 4/5 档双方都会收了，因为双方都不会把 6/7 档给对方」
#   ② 「追 6/7 是可以的，但是风险非常大已经不值得了。这个可以只写在 AI 决策里」
#
# ②定了性质：**规则不禁，是 AI 算出来不划算。** 所以全在决策层，`rules.js` 不动。
#
# 我这边跟①对不上的那个数：g1 在 6/7 档的系数 **+0.04**，
# c=20 时贡献 +0.80，`1,6,20` 那一行的 g1 正是靠它翻正的。
#
# 三段各答一个不同的问题 —— **别把它们的数混着读**：
set -e
# ⚠ **这一行 2026-10-23 晚些补的，别删。** 当天 `HOLD_ONCE` / `HOLD_EV` /
#   `HOLD_BOTH` 三个旋钮的默认值全翻成了「开」，而这个脚本是按**翻之前的默认**写的。
#   这儿还多一条：它用的是 `HOLD_P`，而 `HOLD_EV` 一旦默认开，
#   `HOLD_P` 所在的 `else if` **就到不了了** —— 设了什么都不会发生，静默。
#   下面每一行的 `env X=1` 仍然覆盖这三个，所以本脚本的语义一个字没变。
#   〔2026-10-23 同日再补 `JACK_HOLD=0`：那个旋钮当天也从 0 翻成了 3
#     （用户拍板，见 ai.js 那一行）。**同一个坑的第二次** —— 不钉的话
#     本脚本每一段都变成「守 3 张闸的 AI」跑的，而它写的是「不守」〕
export HOLD_ONCE=0 HOLD_EV=0 HOLD_BOTH=0 JACK_HOLD=0
cd "$(dirname "$0")/../.."
N=${1:-20000}
S=tools/md-sim/sim.js

echo "################################################################"
echo "# A 默认打法：升得了档就忍，一路追到最后一档"
echo "#   —— 这是对照组，不是任何人主张的打法"
echo "################################################################"
node tools/md-sim/band.js -k 3 -n "$N"

echo ""
echo ""
echo "################################################################"
echo "# B 硬上限 HOLD_BAND_MAX=1：目标落在 6/7 往后就不忍"
echo "#"
echo "#   ⚠ 这一段**答不了①**，它会把①变成同义反复 ——"
echo "#     不管 c 多大都不追，c 当然不动天平，那是写死的不是测出来的。"
echo "#"
echo "#   它答的是另一件（也该知道的）事："
echo "#   **把追 6/7 这条路掐掉之后，6/7 档的档值还会不会从别处漏进天平**"
echo "#   —— 堆自己长肥的、J 通吃收走的，那些不归任何人决策。"
echo "#   看 ① 那张表的『判决位』：g1 末档系数掉到 0 = 没漏；仍 ≠ 0 = 漏了。"
echo "################################################################"
node tools/md-sim/band.js -k 3 -n "$N" -m 1

echo ""
echo ""
echo "################################################################"
echo "# C 期望值折扣 HOLD_P=25：**这一段才答①**"
echo "#"
# ⚠ 这一行**不能用反引号**：sh 在双引号里会当成命令替换去执行
#   〔2026-10-22 栽的，输出里多了一条 `升档后的分: command not found`〕
echo "#   「风险非常大已经不值得」写成判据就是：升档后的分 × 25% > 现在的分"
echo "#   25% 不是编的：第一跑实测升档率 24~28%（四组档值）。"
echo "#"
echo "#   它不写死，所以①有了可证伪的形式："
echo "#   **存不存在一个 c，让 6/7 重新变得值得追。**"
echo "#   不存在 → ①的「无论」成立；存在 → ①成立的是「在现行量级上」，"
echo "#   而那个 c 就是设计上的天花板，该写进文档。"
echo "#"
echo "#   ⚠ 这一段**不能用 band.js** —— 折扣判据里带档值，"
echo "#     「打法只认分档结构不认档值」那条前提在这儿破了，离线重算失效。"
echo "#     所以逐组真档值直接跑 sim.js。"
echo "#"
echo "#   读数：先看『期望值折扣改掉 N 次判断/局』。0 = 这一跑等同于不折。"
echo "#   再看『忍了 N 手/局』：c 抬高之后它要是涨起来，就是 6/7 重新值得追了。"
echo "################################################################"
for B in 1,4,12 1,4,20 1,4,40 1,4,100 1,4,400; do
  echo ""
  echo "======== 档值 $B（2/3=1，4/5=4，6/7=c） ========"
  env SCORE_BANDS=$B HOLD_ONCE=1 HOLD_P=25 node $S base -n "$N" 2>&1 | awk '
    /每人每局积分|后手分差/ { print; next }
    /忍 1 手诊断/ { on = 1 }
    on { print }
    /两边都不空|净值看分差/ { on = 0 }
  '
done

echo ""
echo "#### C 段怎么判："
echo "####   『忍了 N 手/局』在 c 抬高的过程中一直不动 → ①的「无论」成立。"
echo "####   在某个 c 上跳起来           → 那个 c 就是 6/7 重新值得追的门槛。"
echo "####   ⚠ 同时盯『后手分差』：忍得更多但分差更负 = 这个 AI 在犯蠢，"
echo "####     不是设计有了决策性。两个数要一起看。"
