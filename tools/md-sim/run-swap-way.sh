#!/bin/sh
# ============================================================================
#  【换水】给【滤饵】让路：先量那个**决定性的数**〔2026-10-22 用户定〕
# ============================================================================
#
#  用户定了两件事：**滤饵 = 抽 3 洗 2**，以及「**改换水来让路**」。
#  而「怎么改」还没定 —— 这一跑是为了把那个决定建立在一个数上。
#
#  ## 一、这一跑真正要回答的那个问题
#
#  我昨天那句「滤饵 N=3 **退 2 张已经吃到换水张数轴的 2/3**」
#  **是个估算，而它可能是错的**，两边的分母我都没量过：
#
#    滤饵 N=3 真换掉几张原手牌 = (returned − fromDrawn)/fires = **1.07**（量过了）
#    换水     真换掉几张原手牌 = swapped/fires               = **没量过**
#
#  而 `rules.js` 换水那段注释里**早就写着这个口该怎么读**：
#    「⚠ 要盯的不是 X，是 `swapped`（真换了几张）—— 要是 AI 平均只换
#      1.2 张，那『任意张数』这个词就是摆设。」
#  同一段还有两个相关的实测：手里那 3 张平均 **2.88 张**当场收不了牌；
#  而 `SWAP_WASTE=0`（强制换满）**只多洗 0.116 张**。
#
#  → 那两条合起来说明 `swapped/fires` 可能已经贴着 2.5~2.8，
#    **于是 1.07 ÷ 它 ≈ 40%，不是 67%** —— 「撞档」就被我说大了，
#    两件在张数轴上本来是错开的，撞的只是 X（1.59 vs 1.73，差 0.14 < 2se）。
#
#  ⚠ **这两种结论要的改动完全相反**：
#    `swapped` 贴 1.2 → 「任意张」是摆设，换水该**把量做实**（加强）
#    `swapped` 贴 2.7 → 两件机制本来就分开，撞的是价，换水该**挪轴或改价**
#  所以先量它，别先选形状。
#
#  ## 二、第 3 节那个 `SWAP_FATE=gone` 是什么
#
#  这是我加的新旋钮（`rules.js` 里有完整墓碑），**唯一一条不把换水调弱的让路**：
#
#    `'deck'`（现状）洗回牌库 → 牌库净 −1、**局长中性**
#    `'gone'`        丢出场外 → 每丢一张牌库真少一张 → **牌库张数 = 局长**
#
#  区分点从「换几张」变成「**废牌还回不回来**」—— 玩家读得懂的差别，
#  而不是一个数值档位。
#
#  ⚠ **它是两刃的，净值我不估**：手牌质量变好（废牌这局不再来），
#    局长变短（双方得分机会一起少）。所以这一档**必须读回合数** ——
#    第 1/3 节诊断第一行那个「我方出牌 N 次/局」，**现状 23.0**。
#    X 涨了而回合数掉了的话，那两件事要分开记，别合成一个「它变强了」。
#
#  ## 三、版本锚：**滤饵 N=3 必须逐位复现**
#
#  我这一跑之前动了 `rules.js`（加 `tossFromHand` + `SWAP_FATE`）。
#  模拟器是**定种的**（mulberry32），所以没碰到的东西该逐位不变：
#
#    滤饵 N=3 · A 槽   该复现 **后手 +1.52 / 先手 +1.66**
#    滤饵 N=3 · ♥ 槽   该复现 **后手 +4.05 / 先手 +4.32**
#    诊断              该复现 fires=1.850 drawn=5.179 returned=3.700 fromDrawn=1.718
#
#  对不上就是我的改动碰坏了别的，**那时候这一跑的数一个都不能用**。
#  （照 CLAUDE.md：定种的模拟器里「两跑一样」要先排除「它本该一样」——
#    这儿是反过来用同一条：**它本该一样，所以不一样就是 bug**。）
#
#  ## 四、口径
#
#  `vs X X` 打两侧原始值：**X = 两侧平均、D = 那个差的一半**
#  （`one` ≡ `all` ≡ `vs`，所以算出来的 X 能直接跟《全技能速查》那列比）。
#  第四行「镜像协同」是**双方都带**那一格 —— 对一件改局长的技能，
#  这一行要单独读（双方一起缩局长，跟单侧不是一回事）。
#
#  **这一跑里换水和滤饵第一次在同一批数里**，所以这两件之间可以直接相减；
#  跟《全技能速查》那列（换水 1.73）相减要先看漂移（见第 5 节）。
#
#  ## 闸
#
#  **这次必须跑** —— 我动了 `rules.js`。`GATE=0` 才跳过。
#
#  旋钮：N=局数 ND=诊断局数 J=并发
set -u
N=${N:-20000}
ND=${ND:-4000}
J=${J:-$(nproc 2>/dev/null || echo 8)}
cd "$(dirname "$0")/../.."
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

pick() {
  grep -E '手里：|先手 − 后手|镜像协同' | head -4 \
    | sed -e 's/^ *//' -e 's/标准误/se/'
}
job() {
  tag=$1; shift
  while [ "$(jobs -rp | wc -l)" -ge "$J" ]; do wait -n 2>/dev/null || break; done
  ( env "$@" >"$TMP/$tag" 2>&1 ) &
}
show() { echo "-- $2"; [ -f "$TMP/$1" ] && cat "$TMP/$1" | pick; }
diag() { echo "-- $2"; [ -f "$TMP/$1" ] && grep -E '出牌|swap:|sift:' "$TMP/$1"; }

if [ "${GATE:-1}" = "1" ]; then
  echo "################ 0. 结构闸（我动过 rules.js，这次必跑）################"
  node tools/md-sim/check.js >"$TMP/check" 2>&1; rc=$?
  node tools/md-sim/refs.js  >"$TMP/refs"  2>&1; rc2=$?
  if [ $rc -ne 0 ] || [ $rc2 -ne 0 ]; then
    cat "$TMP/check"; echo; cat "$TMP/refs"
    echo "!!!! 结构没过（check=$rc refs=$rc2）—— 停，下面的数一个都别看。"
    echo "     ⚠ 这一跑**改过代码**，所以断了很可能就是这一跑弄的。"
    echo "     最可能的落点：tossFromHand 的桶选错了 ——"
    echo "     丢出场外的牌没人收走、不计分，进 G.waste；**进 G.gone 会打断断言三**"
    echo "     （断言三：score 合计 === gone.length）。"
    exit 1
  fi
  echo "全过。"
  grep -E '保护：|白放|waste' "$TMP/check" | head -4
fi

V="node tools/md-sim/sim.js vs"
D="node tools/md-sim/proto-diag.js"
A="--role lock --slot 0"        # A 槽：点数、4 张（窄）= 定价锚槽
H="--role mirror --slot 0"      # ♥ 槽：花色、13 张（宽）
S3="SIFT_DRAW=3 SIFT_BACK=2"

# ---- 1. 现状：换水 vs 滤饵 N=3，同一批数 ----
job xna  $V swap swap -n $N $A
job xnh  $V swap swap -n $N $H
job dna  $D swap $ND 0 lock
job dnh  $D swap $ND 0 mirror
# shellcheck disable=SC2086
job xsa  $S3 $V sift sift -n $N $A
job xsh  $S3 $V sift sift -n $N $H
job dsa  $S3 $D sift $ND 0 lock
# ---- 2. 让路候选甲：降量（SWAP_N=2 / 1） ----
job x2a  SWAP_N=2 $V swap swap -n $N $A
job d2a  SWAP_N=2 $D swap $ND 0 lock
job x1a  SWAP_N=1 $V swap swap -n $N $A
# ---- 3. 让路候选乙：挪轴（SWAP_FATE=gone，丢出场外） ----
job xga  SWAP_FATE=gone $V swap swap -n $N $A
job xgh  SWAP_FATE=gone $V swap swap -n $N $H
job dga  SWAP_FATE=gone $D swap $ND 0 lock
# ---- 4. 对照：强制换满，给 swapped 找天花板 ----
job xfa  SWAP_WASTE=0 $V swap swap -n $N $A
job dfa  SWAP_WASTE=0 $D swap $ND 0 lock
wait

echo
echo "################ 1. 现状两件 · 同一批数（可以相减）################"
show xna "换水（现状：任意张洗回牌库）· A 槽"
show xnh "换水（现状）· ♥ 槽"
show xsa "滤饵 抽3洗2 · A 槽 ← **版本锚：该复现 +1.52 / +1.66**"
show xsh "滤饵 抽3洗2 · ♥ 槽 ← **版本锚：该复现 +4.05 / +4.32**"

echo
echo "################ 2. 那个决定性的数：真换掉几张原手牌 ################"
cat <<'EOF'
〔两件的分母都是 **3**（打出一张之后手里剩 3 张）：
   换水   = `swapped / fires`
   滤饵   = `(returned − fromDrawn) / fires`，上一跑 = **1.07**
 ⚠ 滤饵那一行**不能看 `fromDrawn/returned`** —— 它在抽 N 洗 N−1 这条线上
   被算术顶着涨（≥ (N−4)/(N−1)），不是机制口。
 第一行「我方出牌 N 次/局」是**局长口，现状 23.0** —— 第 3 节要用它。〕
EOF
diag dna "换水（现状）· A 槽"
diag dnh "换水（现状）· ♥ 槽"
diag dsa "滤饵 抽3洗2 · A 槽 ← 该复现 fires=1.850 drawn=5.179 returned=3.700 fromDrawn=1.718"

echo
echo "################ 3. 让路候选甲：降量 ################"
show x2a "换水 SWAP_N=2（只换 2 张）· A 槽"
show x1a "换水 SWAP_N=1（旧档，台账里标『旧档』的那些数就是它）· A 槽"
diag d2a "换水 SWAP_N=2 · 诊断"

echo
echo "################ 4. 让路候选乙：挪轴（丢出场外）################"
cat <<'EOF'
〔⚠ **读这三格的顺序是反的：先读回合数，再读 X。**
   丢出场外 = 牌真离场 = **牌库张数 = 局长**。所以「我方出牌 N 次/局」
   要是从 23.0 掉下来了，X 里就混着两件事（手牌变好 / 局面变短），
   **那两件要分开记，别合成一句「它变强了」**。
   第四行「镜像协同」是双方都带那一格 —— 双方一起缩局长，单独读。〕
EOF
diag dga "换水 SWAP_FATE=gone · 诊断 ← **先看这一行的出牌次数**"
show xga "换水 SWAP_FATE=gone（丢出场外）· A 槽"
show xgh "换水 SWAP_FATE=gone · ♥ 槽"

echo
echo "################ 5. 对照：强制换满（给 swapped 找天花板）################"
cat <<'EOF'
〔`SWAP_WASTE=0` 拆掉「第二张起只换真废牌」那道闸 → 换满 SWAP_N 张。
 它给的是 `swapped` 的**天花板**，而现状那一格离它多远 =
 「挑得准」这件事值多少（照凝水那条：价值全在挑牌精度上）。
 注释里记着旧实测：强制换满**只多洗 0.116 张、亏 0.27 分**。〕
EOF
diag dfa "换水 SWAP_WASTE=0 · 诊断"
show xfa "换水 SWAP_WASTE=0 · A 槽"

echo
echo "################ 6. 怎么读 ################"
cat <<'EOF'
一、**先核版本锚**（第 1 节那两行 + 第 2 节滤饵那一行）。
   对不上 = 我加 `tossFromHand` / `SWAP_FATE` 时碰坏了别的，
   **这一跑的数一个都不能用**。模拟器定种，没碰到的东西该逐位不变。

二、**再读第 2 节那个 `swapped/fires`** —— 它决定要不要动机制：
     贴 1.2 → 「任意张」是摆设，换水该**把量做实**（那是加强，不是让路）
     贴 2.7 → 两件机制本来分开，我说的「撞档」说大了，
               撞的只是 X（1.59 vs 1.73，差 0.14 < 2se）→ 该改的是价/轴

三、第 3、4 节才是两条候选，而**它们不是同一种改动**：
     甲（降量）  同一条轴上往下挪一格，换水从 65 档掉下来
     乙（挪轴）  强弱未定、轴变了，两件的区分点变成「废牌还回不回来」

四、⚠ **定价、命名、上不上架一个都没定** —— 这一跑只出数。
   换水是**上架件**（价 65），动它要改 `draw-skills.uts` + `ap-fishing.uvue`，
   而源码侧没有命令行测试覆盖（`npx jest` 跑不起来，照 CLAUDE.md 第五节）。
   所以**先把数摆齐，形状由你定**。
EOF
