// 游戏里你是人，庄家是这套启发式。模拟里**两侧都用它** ——
// 设计文档那些基础数据（每人每局钓到约 9 次、后手赢 57–59%）标的口径就是
// 「双方都会记牌」，所以要复现那几个数就得两侧同策略。
