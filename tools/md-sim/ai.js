//
// ⚠ **那两行 2026-10-23 加了 `HOLD_BOTH=0`，不加就不是 A/B 了。**
//   `HOLD_BOTH` 当天翻成了默认开（口径要求，见下面那段），而它**不只管忍 1 手**
//   —— `holdSide` 同时被 `HOLD_MIN`（这儿）和 `JACK_HOLD`（:936）读。
