// ⚠ 关掉要显式写 `JACK_HOLD=0`（`'0'` 是真字符串，parseInt 给 0）。
//   不写 = 3，**所有不写它的跑都是守闸的 AI 跑的**。
//
// 🔴 **而它不受 `HOLD_ONCE` 管**（判据在 :1008，只看 `JACK_HOLD > 0 && holdSide`）。
//   2026-10-23 栽的第三次：我手写了一条「退回旧档」的对照命令
