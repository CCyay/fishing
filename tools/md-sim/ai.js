    //   于是「新 AI vs 能吃就吃」那个对战口径里，对面也偷偷聪明了半截。
    //   这正是上面 `holdSide` 那段注释的乙条（三个旋钮共用一道门），现在是四个。
    const anchor = HOLD_ANCHOR && holdSide(side) && keys > 0
    // 原来那一行是 `if (score < pickScore)`，pickScore 初值 99 ——
    // 也就是「分数 ≥ 99 的谁都别选」。那道兜底照旧，只是挪到了前面，
