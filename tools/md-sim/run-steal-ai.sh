#!/bin/sh
# 【抢牌】× 张=分 × 新 AI 对决【能吃就吃】〔2026-10-27〕
#
# 用户：「用「张=分」计分再跑；用 AI 对决【能吃就吃】」
#
# = `run-anchor27.sh` 那一场对战，**搬到抢牌规则下重打一遍**。
# 原来那一场是无抢牌的，而用户已经定了「没有加入抢牌规则，跑这些数据没有用处」。
#
# ---- 口径（跟 `run-anchor27.sh` 逐字相同，只多一个 `STEAL_ON=1`）----
#
# `HOLD_BOTH=0` 一个旋钮同时办两件事（配方在 `ai.js:314-326`）：
#   一 养堆这几条改的是**打法不是技能**，`one`/`all`/`vs` 走 `measureBoth`
#     （双方同角色各插同一槽）→ 两侧一起变聪明 → **量出 0**。只有 `base` 行。
#   二 它顺带**就是用户要的那个对战**：`holdSide(side) = HOLD_BOTH || side === ME`，
#      所以庄家侧 `worthHolding` 在 `ai.js:934` 直接 return false（不养堆）、
#      `JACK_HOLD` 在 :1378、埋锚在 :1798 被同一道门挡掉 —— **那就是【能吃就吃】**。
#
# ⚠ 「能吃就吃」的准确含义：**收牌决策**上纯贪心（能收就收、不捏 J）。
#   挑饵的 `HOLD_PEN`（优先打钓不着的牌）两侧照旧开着 —— 那是「打哪张」
#   不是「收不收」。把它也关掉就不是对战，是喂一个残废对手。
#
# ⚠ **庄家不养堆，可他照样会抢牌。** 抢牌不走 `holdSide` 那道门 ——
#   `stealTry` 是规则，不是打法（`rules.js` 里，不在 `ai.js` 里）。
#   这是对的：抢牌是「对方匹配上了，问你抢不抢」，一个纯贪心的人当然抢。
#
# ---- ⚠⚠ 这一跑最要紧的一条：**养堆 AI 的风险模型是抢牌盲的** ----
#
# `ai.js` 全文搜不到 steal（查过）。`holdEV`（:847）那三个分支是：
#
#   输  对手钓得到我那格或更深 → 我那张被一起收走，什么也没剩
#   平  对手只钓得到我那张以上 → 我那张还在，下一手照收
#   赢  对手一格都钓不着       → 我下一手收 bestCaught + 2 张
#
# **抢牌把这三支全改了，而且方向不一致**：
#
#   输 → 没那么输：他收走一大堆，而**我可以抢回来**（堆越大越好抢）
#   平 → 比「平」好：他收上层，我同样能抢
#   赢 → 没那么赢：我下一手收的时候，**对手可以抢我**
#
# 也就是说抢牌**把养堆的三个分支朝中间压扁**。净偏差是正还是负
# **我没量过，也不打算估** —— 它是这一跑要读的东西之一，而不是前提。
#
# 可量的代理口在 `sim.js` 的抢牌诊断里，**而且是分侧打的**：
#   · 「你」被抢掉 vs「庄家」被抢掉（张/局）—— 养堆那一侧挨抢更多的话，
#     说明「赢支变差」压过了「输支变好」；
#   · 「你」抢走 vs「庄家」抢走（次/局）—— 养堆那一侧抢得更多的话，
#     说明它手里本来就攥着大牌（捏 J 那条打法顺带喂了抢牌）。
# 这两对数**不能当成 holdEV 的偏差值**，它们只定方向。
#
# ---- 读数顺序：**先读计数口，再读比分**（CLAUDE.md 第四节那条）----
#
#   ① `anchorBury` 为 0 而 `anchorNone` 有数 → `keysFor` 没接上，
#      **这一跑的比分一个都不能用**（手里从来没有对子是不可能的）。
#      `sim.js` 自己会把这句 ⚠ 打出来。
#   ② 庄家侧的 `anchorBury` 该跟「关着」那一格一样（被 `holdSide` 挡掉了）。
#      它跟着「你」一起动 = 那道门没接上。
#   ③ 抢牌诊断里「匹配成功 N 次/局」为 0 → `stealTry` 没接上。
#   ④ 两跑的 `reachShal` **不能相减**（关着那跑是「b 支占几手」，
#      开着那跑是「这道闸拦掉了几手」—— 含义不同）。
set -e
OUT=tools/md-sim
N=2000

key() {
  grep -E '^规则 |每人每局积分|每次平均收|后手胜率|后手分差|HOLD_ANCHOR=|扔出去的饵|够得着堆底|掷骰|外面还剩|^    你    忍了|^    庄家  忍了|⚠' "$1"
  sed -n '/抢牌诊断/,/^$/p' "$1"
}

# ---- 第 0 格：回归 ----
#
# 三个旋钮（`STEAL_ON` / `HOLD_BOTH` / `SCORE_BANDS`）都是默认档，
# 所以这一格该跟 `out-a27-regress.txt` **逐位相同**。
# 它不过的话，底下所有格都是在一个被碰坏的基线上跑的。
echo "######## 0 · 回归：全默认档，该跟 out-a27-regress.txt 逐位相同 ########"
node $OUT/sim.js base -n $N > $OUT/out-sai-regress.txt 2>&1
if diff -q $OUT/out-a27-regress.txt $OUT/out-sai-regress.txt > /dev/null; then
  echo "  逐位相同 ✓"
else
  echo "  ✗✗ 对不上 —— 底下几格别读"
  diff $OUT/out-a27-regress.txt $OUT/out-sai-regress.txt | head -20
fi
echo ""

# ---- 一、四格矩阵（张=分 · 抢牌 · 对战能吃就吃）----
#
# ⚠ **乙丙必须分开量，不能一起开报一个数** —— 丙（埋锚）制造的正是
#   乙（够得着）的前提（埋下一张我握着钥匙的牌 = 把 b 变成 a），
#   两条是**耦合**的，所以是四格，不是两格。
#
# `SCORE_BANDS=off` = 张=分。**必须显式写** —— 不写现在是 R4。
cell() {
  anchor=$1; reach=$2
  echo "######## 张=分 · 抢牌 · HOLD_ANCHOR=$anchor HOLD_REACH=$reach · 你(新AI) vs 庄家(能吃就吃) ########"
  SCORE_BANDS=off STEAL_ON=1 HOLD_BOTH=0 HOLD_ANCHOR=$anchor HOLD_REACH=$reach \
    node $OUT/sim.js base -n $N > $OUT/out-sai-z$anchor$reach.txt 2>&1
  key $OUT/out-sai-z$anchor$reach.txt
  echo ""
}
cell 0 0
cell 1 0
cell 0 1
cell 1 1

# ---- 二、【按概率忍】三档 ----
#
# 用户 2026-10-27：「算出忍的概率后，可以用生成随机数的方法，
# 如果随机数落在概率里就忍。」三档各对应一个现成的概率量：
#   `pwin` = 对手一格都钓不着（真赚那一支）
#   `keep` = 1 − pLose = 我那张没被一起收走（含「只有饵被吃」，必然更大）
#   `gate` = 先过 EV 硬闸再掷骰 —— **只会忍得更少**，「少忍有没有好处」那一格
#
# ⚠⚠ **这三格跟上面四格不是同一批牌。** 掷骰要从 `G.rng` 取数，而那是
#   整局共用的那条序列（发牌、补牌都从它取）—— 多掷一次后面所有牌都换了。
#   所以跟 `off` 那格的差里掺着「不同的牌」，2000 局下**要看 se**，
#   而「逐位相同」这种回归**对这三格无效**。判据在 `ai.js` 的 `HOLD_MIX` 那段。
#
# ⚠ 这三个概率**也是抢牌盲的**（它们是从 holdEV 同一套分支算出来的）。
#   所以「按概率忍」在抢牌下忍的频率对不对，这一跑答不了 —— 它只答
#   「用这个概率去掷骰，比硬闸好还是差」。
for m in pwin keep gate; do
  echo "######## 张=分 · 抢牌 · HOLD_MIX=$m（埋锚+够得着都开）· 你 vs 庄家(能吃就吃) ########"
  SCORE_BANDS=off STEAL_ON=1 HOLD_BOTH=0 HOLD_ANCHOR=1 HOLD_REACH=1 HOLD_MIX=$m \
    node $OUT/sim.js base -n $N > $OUT/out-sai-mix-$m.txt 2>&1
  key $OUT/out-sai-mix-$m.txt
  echo ""
done

# ---- 三、分侧看抢牌：养堆那一侧是挨抢的还是抢人的 ----
#
# 这是文件头那条「抢牌盲」的唯一测量口，所以单独并排打一次。
# 读法见文件头 —— 它**只定方向，不是 holdEV 的偏差值**。
echo "######## 3 · 分侧抢牌诊断：关关（00）vs 都开（11）########"
echo "  —— 00（养堆AI 基础档）——"
sed -n '/抢牌诊断/,/^$/p' $OUT/out-sai-z00.txt
echo "  —— 11（埋锚 + 够得着都开）——"
sed -n '/抢牌诊断/,/^$/p' $OUT/out-sai-z11.txt
