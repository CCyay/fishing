#!/bin/sh
# 第一跑之后补的两个缺口〔2026-10-27〕
#
# 第一跑（`run-anchor27.sh`）出了一个**反转**：同一套养堆 AI，
#   R4   下对「能吃就吃」**+2.94 分 / 胜率 58.8%**
#   张=分 下对同一个对手 **−0.87 分 / 胜率 45.4%**
# 而张=分那边 AI 自己几乎不忍了（0.40 手/局，R4 是 1.20）——
# 线性计分下「放弃 2 张换 4 张」没有档跳可赚，EV 自己把忍关掉了。
#
# 于是第一跑的两个结论各缺一格：
#
# 甲 **`HOLD_MIX` 只在张=分下量过**，而那是一个「养堆本身就亏」的世界 ——
#    在那儿多忍当然更亏（keep 多忍 2.69 次/局 → −5.11 分）。
#    那是**计分档的结论，不是 MIX 的结论**。R4 下忍是赚的（+2.94），
#    所以 MIX 在 R4 下完全可能是正的。这三格补上。
#
# 乙 **埋锚的 +0.23 在 2000 局下只有 0.9σ**（se 0.25）。它的可信之处在于
#    **复现了三次**：张=分 REACH=0 下 +0.23、REACH=1 下 +0.23、
#    R4 下 +0.27 —— 三次同向同量，而且机制计数跟着动
#    （饵自己收得回来 26.1% → 31.5%，庄家侧 30.1% → 30.4% 没动 ⇒ 门接对了）。
#    但「三次 0.9σ」不等于一次 2σ，所以 R4 那两格重跑 20000 局。
set -e
OUT=tools/md-sim
key() {
  grep -E '每人每局积分|每次平均收|后手胜率|后手分差|HOLD_ANCHOR=|扔出去的饵|够得着堆底|掷骰|外面还剩|^    你    忍了|⚠' "$1"
}

# ---- 甲：R4 下的 MIX 三档（2000 局，先看幅度）----
for m in pwin keep gate; do
  echo "############ R4 · HOLD_MIX=$m（埋锚+够得着都开）· 你 vs 庄家(能吃就吃) ############"
  HOLD_BOTH=0 HOLD_ANCHOR=1 HOLD_REACH=1 HOLD_MIX=$m \
    node $OUT/sim.js base -n 2000 > $OUT/out-a27b-r4mix-$m.txt 2>&1
  key $OUT/out-a27b-r4mix-$m.txt
  echo ""
done

# ---- 乙：R4 下埋锚两格重跑 20000 局（se 0.25 → 约 0.08）----
#
# ⚠ 这两格**跟上面三格不是同一批牌也不是同一局数**，别混着减。
#   能减的只有这两格**互相**（同种子、同局数、同代码、只差一个旋钮）。
for a in 0 1; do
  echo "############ R4 · 20000 局 · HOLD_ANCHOR=$a HOLD_REACH=$a · 你 vs 庄家(能吃就吃) ############"
  HOLD_BOTH=0 HOLD_ANCHOR=$a HOLD_REACH=$a \
    node $OUT/sim.js base -n 20000 > $OUT/out-a27b-r4-$a.txt 2>&1
  key $OUT/out-a27b-r4-$a.txt
  echo ""
done
