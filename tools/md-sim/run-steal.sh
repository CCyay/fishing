#!/bin/sh
# 【抢牌】第二跑：连续抢定稿之后〔2026-10-27〕
#
# 规则（用户原话，逐句落地在 `rules.js` 的 `stealTry` 那一段）：
#   「一方打出牌实现匹配（点数相同的匹配）后不立即收牌，先询问对方是否抢牌。
#     抢牌就是你可以打出 1 张牌，只要收的比对方多，你就可以抢先收牌」
#   「J 也可以被抢，所有能收整堆的都能互相抢」
#   「三、抢牌成功后，双方补齐手牌，转入对方(未抢到者)回合」
#   「**连续抢 要开启**」〔2026-10-27 定 → `STEAL_AGAIN` 默认翻成开〕
#
# ⚠ **单轮抢那一批数作废**（用户：「不带连续抢的数据就不要了」）。
#   第一跑的 R4 单轮格（3.90 张/次 · 19.5 分）和张=分单轮格
#   （3.66 · 21.9）别再引用，台账里划掉别删。
#   `STEAL_AGAIN=0` 这个旋钮**留着**，但它现在只是个 A/B 口，不是档位。
#
# ---- 考量标准是**平均收牌张数**（用户定的）----
#
# 「牌堆常态就不适合作为考量标准了，应该把平均收牌张数作为考量标准」
#
# ⚠⚠ **总平均张数会涨，而那个涨幅里有一部分是同义反复** —— 抢牌的判定
#   条件就是「收得比对方多」，于是每个匹配事件的收成从「A 的张数」
#   变成「max(A, B 能拿的最大)」，**行为一个字不变它也会涨**。
#   所以 `sim.js` 拆成四路互斥报（普通匹配 / J 通吃 / 抢·非J / 抢·J）。
#
# ⚠⚠⚠ 可**「普通匹配」那一格也有选择偏差，而且方向是朝上的**
#   〔2026-10-27 第一跑之后才想清的，比上面那条更隐蔽〕：
#   抢牌下的「普通匹配」= **没被抢走的那些匹配**，而收成越大越难被超过
#   （要抢得拿出更大的），所以**大收成存活率更高** → 这一格天生偏高。
#   于是它**不能**单独当「养堆行为变了」的证据。
#
#   真正干净的行为诊断口是下面第 2 节那张「**出牌时堆有多厚**」——
#   它是整个总体，没有存活筛选。用户把「牌堆常态」从*考量标准*里拿掉了，
#   可它作为**行为诊断**仍然是对的（那两件事不一样：标准是用来定优劣的，
#   诊断是用来确认机制接上了的）。
#
# ⚠ 第三条读数纪律：**平均收牌张数不是胜负的代理**。实测过一次反转 ——
#   养堆那一侧 3.21 张/次 vs 2.79，**可总分输了**（21.3 vs 22.2），
#   因为收牌次数掉了。而抢牌这一跑正是这个形状：次数降、张数升，
#   **乘起来几乎不变**（守恒：牌就那么多）。所以必须「次数 × 张数」一起读。
set -e
OUT=tools/md-sim
N=2000

key() {
  grep -E '规则档|每人每局积分|每次平均收|后手胜率|后手分差|^  自检|⚠⚠' "$1"
  sed -n '/抢牌诊断/,/^$/p' "$1"
}

# ---- 第 0 格：回归。`STEAL_ON` 默认关 ⇒ 默认跑必须跟改之前**逐位相同** ----
#
# ⚠ **翻了 `STEAL_AGAIN` 默认值之后这一格更要跑** —— 它证明那次翻动
#   没漏到 `STEAL_ON=0` 这条路上来（`STEAL_AGAIN` 只在 `stealTry` 里读，
#   而 `stealTry` 第一行就被 `STEAL_ON` 挡掉了，所以**该**逐位相同）。
echo "######## 0 · 回归：STEAL_ON 默认关，该跟 out-a27-regress.txt 逐位相同 ########"
node $OUT/sim.js base -n $N > $OUT/out-steal-off.txt 2>&1
if diff -q $OUT/out-a27-regress.txt $OUT/out-steal-off.txt > /dev/null; then
  echo "  逐位相同 ✓"
else
  echo "  ✗✗ 对不上 —— 底下几格别读，先查 stealTry 是不是漏了 STEAL_ON 这道闸"
  diff $OUT/out-a27-regress.txt $OUT/out-steal-off.txt | head -20
fi
echo ""

# ---- 一、抢牌（连续抢，定稿档）× 两个计分档 ----
#
# 用户 2026-10-27：「R4 是分段记分，在抢牌规则下要调整了。因为在抢牌下
# **收 4 张的概率也变了**。要重新算计分方法，**原先的张=分 也可以回来考虑**。」
#
# ⚠ 跨计分档**不能比绝对分**（R4 每人每局 21.8 / 张=分也是 21.8，但那是
#   巧合不是可比 —— 张=分下积分恒等于张数，而张数是守恒的）。
#   能比的只有**后手分差 / 胜率 / 每次收牌张数 / 收牌次数**这几样口径无关的。
echo "######## 1 · R4 · 抢牌（连续抢）########"
STEAL_ON=1 node $OUT/sim.js base -n $N > $OUT/out-steal-r4.txt 2>&1
key $OUT/out-steal-r4.txt
echo ""
echo "######## 1 · 张=分 · 抢牌（连续抢）########"
SCORE_BANDS=off STEAL_ON=1 node $OUT/sim.js base -n $N > $OUT/out-steal-z.txt 2>&1
key $OUT/out-steal-z.txt
echo ""

# ---- 二、行为诊断：堆到底有没有变厚 ----
#
# 用户预测的那条机制：「比如我手里有对子（两个 3），在堆底打出 1 张 3 后，
# 就可以放心堆牌了。而对方不确定你手牌是否有 3 或者自己手牌有 3 或 J，
# **对方也会放心堆牌**。」
#
# 这张表是那句话**唯一没有存活偏差的**验证口（见文件头 ⚠⚠⚠）。
# 读法：分布整体右移 = 双方真的在养堆；不动 = 抢牌只是换了个人收。
echo "######## 2 · 出牌时堆有多厚：抢牌 vs 无抢牌（行为诊断，无存活偏差）########"
echo "  —— 抢牌（连续抢 · R4）——"
sed -n '/出牌时堆有多厚/,/自检/p' $OUT/out-steal-r4.txt | head -5
echo "  —— 无抢牌（R4，对照）——"
sed -n '/出牌时堆有多厚/,/自检/p' $OUT/out-steal-off.txt | head -5
echo ""

# ---- 三、收 N 张的难度曲线：重定计分的输入 ----
#
# 用户那句「收 4 张的概率也变了」的直读。读「**非J台阶**」那一列
# （P(N)/P(N−1)）—— 线性积分对应的是那一列恒等于 1，台阶越陡越需要分档。
echo "######## 3 · 收 N 张的难度曲线（抢牌 · R4）—— 重定计分的输入 ########"
sed -n '/收 N 张的难度曲线/,/出牌时堆有多厚/p' $OUT/out-steal-r4.txt
echo ""
echo "######## 3 · 同一张表（无抢牌 · R4）—— 对照组 ########"
sed -n '/收 N 张的难度曲线/,/出牌时堆有多厚/p' $OUT/out-steal-off.txt

# ---- 四、解计分：`band.js` 在抢牌下还成立，而这一句得先说清 ----
#
# `band.js` 的全部前提是「**打法只认分档结构、不认档值**」，于是一个结构
# 跑三格拿直方图、任意档值离线精确重算。**抢牌没有破掉这条前提** ——
# 抢牌的判定条件是用户写的「只要收的**比对方多**」，那是对 **N** 的比较、
# 不读 `scoreOf`，所以跟贪心挑牌一样对档值不变。
#
# `STEAL_ON` 不在 `fn.js` 的 `ENV_PIN` 里（那四个钉子是给「翻过默认值」的
# 旋钮留的），所以它从外面的 shell 直接传进三格 —— 而**验证口是
# `band.js` 第一行新印的「规则档」**（2026-10-27 补的，见那段注释）。
# 那一行没写 `STEAL_ON=1` 的话，这一屏是无抢牌的数，别读。
echo ""
echo "######## 4 · 抢牌下重解档值（3 档结构）########"
echo "〔慢：三格 ×20000 局〕"
STEAL_ON=1 node $OUT/band.js -k 3
