#!/bin/sh
# 【埋锚】× 【够得着才养堆】四格矩阵 + 跟【能吃就吃】对战〔2026-10-27〕
#
# 用户那两句：
#   「先把 AI 实现了，再按『张 = 分』跑一下（2000次）」
#   「AI 出来后，要跟【能吃就吃】对战看看比分」
#
# 规格原话（情景1，堆底是 3）：
#   a：手牌有 3 或 J，要计算牌组和对方手牌有 3 或 J 的概率。
#   b：手牌无 3 或 J。一般不建议 AI 在 b 下养堆。
#   a 下也要科学养堆，手牌 J 越多、对方 3 或 J 的概率越小时越要养堆。
#   在手牌有对子时要优先打（把匹配牌埋到深处）。
#
# ---- 规格的三条分别落在哪儿（逐句核过，不是概括） ----
#
#   甲「a 下算概率，J 越多越要养堆」→ **`holdEV` 早就是这个，一行新代码都没加**。
#      `missP` 是精确超几何（U = 牌库 + 对手手牌），`foeReachOf` 包的是
#      `R.catchStart`（唯一入口，所以 **J 通吃自动在风险模型里**），
#      而 `outsideCount` 已经减掉我自己的手牌 —— 于是「手里 J 越多 →
#      对方有 J 的概率越小」**自动成立**。再写一份就是那条墓碑
#      （「复制一份逻辑，两份必然分叉」）。
#   乙「b 下别养堆」            → `HOLD_REACH`（`worthHolding` 末尾那道闸）
#   丙「有对子优先打，埋到深处」→ `HOLD_ANCHOR`（挑饵循环里新加的一层排序）
#
# ⚠ **乙丙必须分开量，不能一起开报一个数** —— 丙制造的正是乙的前提
#   （埋下一张我握着钥匙的牌 = 把 b 变成 a），两条是**耦合**的，
#   所以是四格（关关 / 只丙 / 只乙 / 都开），不是两格。
#
# ---- 为什么这一跑必须 `HOLD_BOTH=0`（两个理由，缺一个都读不出数） ----
#
#   一 **这两条改的是打法不是技能**，而 `one`/`all`/`vs` 走 `measureBoth`
#     （双方同角色各插同一槽），两侧一起变聪明 → **量出 0**。
#      配方写在 `ai.js:314-326`：`HOLD_BOTH=0` + `sim.js base`。
#   二 它顺带**就是用户要的那个对战**：`holdSide(side) = HOLD_BOTH || side === ME`，
#      所以 `HOLD_BOTH=0` 下庄家侧 —— `worthHolding` 在 :934 直接 return false
#      （不养堆）、`JACK_HOLD` 在 :1378 被同一道门挡掉（不捏 J）、
#      埋锚在 :1798 被同一道门挡掉 —— **就是【能吃就吃】**。
#
# ⚠ 「能吃就吃」在这儿的准确含义：**收牌决策**上纯贪心（能收就收、不捏 J）。
#   挑饵的 `HOLD_PEN`（优先打钓不着的牌）两侧照旧开着 —— 那是「打哪张」
#   不是「收不收」，把它也关掉就不是对战而是喂一个残废对手了。
#   读比分时这一句要跟着写进台账，不然下一轮会以为对面是全随机。
#
# `base` 口径（`sim.js:684-688`）：双方**空槽**、`freeFirst: true`（切牌定庄，
# 先手机会均等）。所以「你」vs「庄家」两列是干净的 A/B，**不含先后手常数**。
set -e
OUT=tools/md-sim
N=2000

# 只打要读的几行 —— 全文一格 45 行、七格 300 多行，读不动。
# 全文照旧留在 `out-a27-*.txt` 里（反常的时候要回去看原文，别凭这几行解释）
key() {
  grep -E '每人每局积分|每次平均收|后手胜率|后手分差|HOLD_ANCHOR=|扔出去的饵|够得着堆底|掷骰|外面还剩|^    你    忍了|^    庄家  忍了|⚠' "$1"
}

# ---- 第 0 格：回归。两个新开关默认关 ⇒ 默认跑必须跟改之前**逐位相同** ----
#
# 必须先过这一格。它不过的话，底下四格的数全是在一个被我碰坏的基线上跑的。
# 核对项（R4、`base`、同种子）：六个数 + 后手分差 + 胜率，跟台账现行 R4 那一节对。
# ⚠ 后手分差有**两个口径**：`base` 是混合（自由切牌）≈ −0.07，
#   而「固定先后手」那个 +0.31 是另一节的数 —— 拿 +0.31 来核这一格会去查一个
#   不存在的 bug（2026-10-21 栽过）。
echo "############ 0 · 回归：默认档（两开关关 · R4）该跟改前逐位相同 ############"
node $OUT/sim.js base -n $N > $OUT/out-a27-regress.txt 2>&1
cat $OUT/out-a27-regress.txt
echo ""

# ---- 四格矩阵（张=分 · 对战能吃就吃）----
#
# `SCORE_BANDS=off` = 张=分（R3 的计分）。**必须显式写** ——
# 不写现在是 R4（`rules.js:9484-9485`）。
cell() {
  anchor=$1; reach=$2
  echo "############ 张=分 · HOLD_ANCHOR=$anchor HOLD_REACH=$reach · 你(新AI) vs 庄家(能吃就吃) ############"
  SCORE_BANDS=off HOLD_BOTH=0 HOLD_ANCHOR=$anchor HOLD_REACH=$reach \
    node $OUT/sim.js base -n $N > $OUT/out-a27-z$anchor$reach.txt 2>&1
  key $OUT/out-a27-z$anchor$reach.txt
  echo ""
}

# ---- 读数顺序：**先读计数口，再读比分** ----
#
# 这不是讲究，是 CLAUDE.md 第四节那条（同色闸 bug 下 4.89 / 修好 4.88，
# 单看 X 永远发现不了）。具体三道：
#
#   ① `anchorBury` 为 0 而 `anchorNone` 有数 → `keysFor` 没接上，
#      **这一跑的比分一个都不能用**（手里从来没有对子是不可能的）。
#      `sim.js` 会自己把这句 ⚠ 打出来。
#   ② `reachDeep` / `reachShal` 的占比 —— 关着那一跑是**对照组的分母**
#      （b 支占多少手），开着那一跑的 `reachShal` 含义变成「这道闸拦掉了几手」。
#      ⚠ **两跑的 `reachShal` 不能相减**，含义不同。
#   ③ 庄家侧的 `anchorBury` 该跟「关着」那一格一样（它被 `holdSide` 挡掉了，
#      挑到带钥匙的饵纯属碰巧）—— 它要是跟着「你」一起动，那道门没接上。
cell 0 0
cell 1 0
cell 0 1
cell 1 1

# ---- R4 下的同一场对战（两格）----
#
# 用户的顺序是「先定计分，再定标准」，所以这两格不是附赠 ——
# **它是「张=分 能不能回来」那个判断的另一半**：
# R4 的 b/a=4 是在**升级前的 AI** 上定出来的最小值（`rules.js:9476-9482`），
# 而现在 AI 的直方图变了。两个计分档下各跑「关关 / 都开」，
# 才看得出这套打法的收益是**不是**靠 R4 的分档结构放大出来的。
#
# ⚠ 跨计分档**不能比绝对分**（R4 每人每局 21.8 / 张=分不是这个数）——
#   能比的只有**后手分差、胜率、平均每次收牌张数**这三样口径无关的。
for a in 0 1; do
  echo "############ R4 · HOLD_ANCHOR=$a HOLD_REACH=$a · 你(新AI) vs 庄家(能吃就吃) ############"
  HOLD_BOTH=0 HOLD_ANCHOR=$a HOLD_REACH=$a \
    node $OUT/sim.js base -n $N > $OUT/out-a27-r4-$a.txt 2>&1
  key $OUT/out-a27-r4-$a.txt
  echo ""
done

# ---- 【按概率忍】三档（用户 2026-10-27：「随机数落在概率里就忍」）----
#
# 「忍的概率」在现行模型里有两个现成的量，差得远，所以两档都量：
#   `pwin` = 对手一格都钓不着（真赚那一支，判忍的手上实测均值 49.8%）
#   `keep` = 1 − pLose = 我那张没被一起收走（含「只有饵被吃」，必然更大）
#   `gate` = 先过 EV 硬闸再掷骰 —— **只会忍得更少**，它是「少忍有没有好处」的那一格
#
# ⚠⚠ **这三格跟上面所有格不是同一批牌。** 掷骰子要从 `G.rng` 取数，
#   而那是整局共用的那条序列（发牌、补牌都从它取）—— 多掷一次
#   后面所有牌就都换了。所以：
#     · 跟 `off` 那一格的差里掺着「不同的牌」，2000 局下要看 se；
#     · 「逐位相同」这种回归**对这三格无效**。
#   判据写在 `ai.js` 的 `HOLD_MIX` 那段 ⚠⚠。
for m in pwin keep gate; do
  echo "############ 张=分 · HOLD_MIX=$m（埋锚+够得着都开）· 你 vs 庄家(能吃就吃) ############"
  SCORE_BANDS=off HOLD_BOTH=0 HOLD_ANCHOR=1 HOLD_REACH=1 HOLD_MIX=$m \
    node $OUT/sim.js base -n $N > $OUT/out-a27-mix-$m.txt 2>&1
  key $OUT/out-a27-mix-$m.txt
  echo ""
done
