#!/bin/sh
# **R3 → R4 翻默认值的验收**〔2026-10-23 第十跑〕
#
# 用户定了两件：① 档值定稿 `1,4,12`；② `HOLD_RUN` 锁死在 1。
# 翻默认值是 CLAUDE.md 点名的**两类不会自己提醒你**的基准变更之一
#（墓碑：`WADE_SELF` —— 改了定稿忘了翻默认值，整张 `all` 表拿旧档的数定了新档的价）。
#
# ---- 这一跑只证四件事，不出新结论 ----
#   一、**退得回去**：`SCORE_BANDS=off` 必须逐位复现 R3 基线
#   二、**翻对了**  ：不写 env == 显式写 `1,4,12`（默认值真的是它）
#   三、**锁住了**  ：`HOLD_RUN=2` 这个 env 必须**完全不起作用**
#   四、**R4 的新基线**：往后所有重量都拿它当底
set -e
# ⚠ **这一行 2026-10-23 晚些补的，别删。** 当天 `HOLD_ONCE` / `HOLD_EV` /
#   `HOLD_BOTH` 三个旋钮的默认值全翻成了「开」，而这个脚本是按**翻之前的默认**写的。
#   这儿最要紧的是甲、乙两段（「`SCORE_BANDS=off` 必须逐位复现 R3 基线」）——
#   它们一个 HOLD_* 都不写，翻了默认之后**会变成会忍的 AI 跑的**，
#   于是那条「退得回去」的自检必然失败，而失败的原因跟 `SCORE_BANDS` 毫无关系。
#   下面每一行的 `env X=1` 仍然覆盖这三个，所以本脚本的语义一个字没变。
#   〔2026-10-23 同日再补 `JACK_HOLD=0`：那个旋钮当天也从 0 翻成了 3
#     （用户拍板，见 ai.js 那一行）。**同一个坑的第二次**，而这儿照样是
#     甲、乙两段最要紧：「`SCORE_BANDS=off` 必须逐位复现 R3 基线」那条自检
#     会因为 AI 换了打法而失败，而失败的原因跟 `SCORE_BANDS` 毫无关系。
#     丁、戊两段要的是第九跑甲段（+0.90 / 26.1% / 1.78），那一跑**没开 JACK_HOLD**，
#     所以这儿也必须是 0 —— 不钉的话丁段会打成 +3.06 量级，读成「没锁住」〕
export HOLD_ONCE=0 HOLD_EV=0 HOLD_BOTH=0 JACK_HOLD=0
cd "$(dirname "$0")/../.."
N=${1:-20000}
S=tools/md-sim/sim.js

eight() { grep -E "后手分差|后手胜率|每人每局|平均收|每次收|出牌|钓到"; }

echo "######## 零 规则层不变量 ########"
echo "〔check.js 的三之二那条自检改了判据（env → R.SCORE_BANDS）。"
echo "  不改的话默认开着时它会**当场误报**，所以这一段是那个改动的验收〕"
node tools/md-sim/check.js 2>&1 | tail -6
node tools/md-sim/refs.js 2>&1 | tail -3

echo ""
echo "######## 甲 退得回去：SCORE_BANDS=off 必须 == R3 基线 ########"
echo "〔要的八个数：后手分差 −0.07(se 0.08)、胜率 48.1%、每人每局 21.8 分、"
echo "  每次平均收 2.85、钓到 7.7 次、出牌 23.0。**对不上就是我改坏了 scoreOf**〕"
env SCORE_BANDS=off node $S base -n "$N" 2>&1 | eight

echo ""
echo "######## 乙 R4 新基线：什么 env 都不写 ########"
echo "〔「每人每局」会**整个换一个量级**（档值不是张数），那是对的。"
echo "  而**张数口径那几列（每次平均收 / 钓到 / 出牌）该跟甲段一字不差** ——"
echo "  计分不改打法。不一样的话说明 scoreOf 漏进了选牌判据〕"
node $S base -n "$N" 2>&1 | eight

echo ""
echo "######## 丙 翻对了没：显式写 1,4,12 必须 == 乙段 ########"
env SCORE_BANDS=1,4,12 node $S base -n "$N" 2>&1 | eight

echo ""
echo "######## 丁 **锁住了没**：HOLD_RUN=2 必须完全不起作用 ########"
echo "〔口径照第九跑的甲段：HOLD_ONCE=1 HOLD_EV=1。"
echo "  要的是 **+0.90(se 0.08) / 判忍 26.1% / 忍了 1.78 手**（= 第九跑甲段）。"
echo "  打出 **+1.86 / 28.4% / 2.35**（= 第九跑庚段）就是**没锁住**，env 还在被读〕"
env HOLD_ONCE=1 HOLD_EV=1 HOLD_RUN=2 node $S base -n "$N" 2>&1 \
  | grep -E "后手分差|忍了|判忍|HOLD_RUN"

echo ""
echo "######## 戊 锁死之后的现行打法（HOLD_ONCE + HOLD_EV，不写档值）########"
echo "〔该逐位复现第九跑甲段 —— 它那时显式写了 1,4,12，现在那是默认值〕"
env HOLD_ONCE=1 HOLD_EV=1 node $S base -n "$N" 2>&1 | eight

echo ""
echo "#### 怎么判（五条，任一条不过都别往下用）："
echo "####   一、甲段八个数 != R3 → **scoreOf 的 off 分支写坏了**，后面全不作数。"
echo "####   二、乙段「每次平均收 / 钓到 / 出牌」!= 甲段 → 计分漏进了选牌判据。"
echo "####      〔注：rules.js 那段注释说过打法只认**分档结构**不认档值，"
echo "####        但「分档 vs 不分档」是两个结构，所以这三列**理论上可以不等**。"
echo "####        真不等的话不是 bug，是 ai.js「平手取张数多」那条 tie-break 在动 ——"
echo "####        **先看差多少，再决定要不要查**，别一看见不等就改代码〕"
echo "####   三、丙段 != 乙段 → 默认值没翻成 1,4,12。"
echo "####   四、**丁段 == 第九跑甲段**（+0.90 / 26.1% / 1.78）→ 锁住了。"
echo "####      等于庚段（+1.86 / 28.4% / 2.35）→ 哪儿还在读 HOLD_RUN，去 grep。"
echo "####      诊断头那行该打 `HOLD_RUN=1（锁死）`，打别的就是 sim.js 又写了份副本。"
echo "####   五、戊段 == 第九跑甲段 → 这就是 R4 的现行打法，记进台账 §三。"
