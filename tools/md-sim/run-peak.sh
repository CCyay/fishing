#!/usr/bin/env bash
# 2026-10-20 ·「把点数堆高、再用【齐顶】收割」这条思路的立项测量。
#
# 照 16.9【涌泉】那条「立项前必须跑的三件，顺序不能换」——
# **pair 先跑**：这条思路是「一件造局面、另一件兑现」的两件式，
# 而那是全表被证伪得最彻底的架构（压底族 6 + 合流 + 抄底，八件一个不剩）。
# pair 不出协同就不要做。
#
# ⚠ 跑之前先修了一处漂移：模拟器的齐顶**漏了「同色无点数 → 抄到无点数」**
# 那一支（源码 ap-fishing.uvue:4850 一直有）。那是齐顶唯一的天然反制，
# 所以台账里 3.57 那一行**偏高、作废**。第 0 节就是重量它。
set -u
N=${N:-20000}
cd "$(dirname "$0")/../.."

echo "################ 0. 齐顶重量（漂移修完之后） ################"
node tools/md-sim/check.js 2>&1 | tail -3
echo "---- 齐顶 · 修完（台账旧数 3.57 作废） ----"
node tools/md-sim/sim.js vs peak peak -n "$N" | sed -n '1,12p'
echo "---- 齐顶 · 花色槽（幅度跟槽型有关，两种都要量） ----"
node tools/md-sim/sim.js one peak --role night --slot 0 -n "$N" | sed -n '1,8p'

echo
echo "################ 1. 这条思路的核心一格：抬水 × 齐顶 ################"
# 【抬水】是现成的「提升点数」件（垫在下面 +牌面点数，随即判匹配）。
# 它跟齐顶的组合**零成本就能量**，而且它是这条路唯一的立项依据。
#
# ⚠ 这一格**可能是负的**，而理由事前就看得见：抬水的 AI 挑法
#（pilePick 里 SK.RAISE 那支）是为「自己撞上同点数、那一段最长」优化的，
# **不是为齐顶优化的**。抬错了牌会把齐顶的落点推浅（抬堆顶那张 =
# top 在堆顶 = 只收 1 张），所以这个组合有**反效果**的可能
node tools/md-sim/sim.js pair raise peak -n "$N"

echo
echo "################ 2. 对照：另两件能改点数的 ################"
echo "---- 归深 × 齐顶（它追加 11 点 —— 堆上没有 11，所以它是「造一个新 top」） ----"
node tools/md-sim/sim.js pair deep peak -n "$N"
echo "---- 软点 × 齐顶（追加 1 点，方向相反：它**降低**不了 top，应该近 0） ----"
node tools/md-sim/sim.js pair soft peak -n "$N"

echo
echo "################ 3. 齐顶的落点到底在哪（决定这条路的天花板） ################"
# 这条思路的全部收益 = 「把落点从随机位置挪到堆底」。
# 而堆常年 2.1 张厚 —— 从中间收和从底收**差不到 1 张**。
# 这一格量的是齐顶现在每次收几张，它直接给出天花板
node tools/md-sim/sim.js one peak -n "$N" | sed -n '1,14p'

echo
echo "################ 跑完 ################"
